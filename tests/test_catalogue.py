"""Tests of lattice.catalogue: each lattice is identified by invariants that determine it.

An even lattice generated by its roots (vectors of norm 2) is the orthogonal sum given by its root
system, and in each rank the number of roots distinguishes A_n, D_n and E_n (A_3 = D_3); so for the
root lattices it suffices to check the rank, the determinant, the number of roots and that the roots
generate the lattice. A unimodular lattice with 2n vectors of norm 1 is Z^n. An even unimodular
positive definite lattice of rank 24 without roots is the Leech lattice (Conway).
"""
from collections import Counter
import numpy as np
import pytest
from lattice._matrix import imat, imat_diag, imat2flz
from lattice.lattice import Lattice
from lattice.catalogue import (A_lat, B_lat, C_lat, D_lat, E_lat, U_lat, I_lat, II_lat_n_1, Leech_lat,
                               Leech_lat_alt, E_lat_test)
from lattice import fp_search_cpp


def short_vectors(L, bound):
    """The vectors v of the positive definite lattice L with 0 < (v, v) <= bound (both v and -v)."""
    A = np.array(L.A.tolist(), dtype=float)
    return [imat([int(x) for x in v]) for v in fp_search_cpp.FPSearch(A, np.zeros(L.rank), 0.5, bound + 0.5).search_all()]


def norms(L, bound):
    return dict(Counter(L.square(v) for v in short_vectors(L, bound)))


def check_root_lattice(L, rank, det, nroots):
    assert L.rank == rank and L.signature == (rank, 0) and not L.parity
    assert int(L.A_fl.det()) == det
    roots = short_vectors(L, 2)
    assert len(roots) == nroots
    # The roots generate L
    assert imat2flz(imat(roots)).rank() == rank and Lattice.index(imat(roots)) == 1


@pytest.mark.parametrize("n", range(1, 9))
def test_A(n):
    check_root_lattice(A_lat(n), n, n + 1, n * (n + 1))
    assert A_lat(n).dgroup[-1] == n + 1


@pytest.mark.parametrize("n", range(2, 9))
def test_D(n):
    check_root_lattice(D_lat(n), n, 4, 2 * n * (n - 1))
    # The discriminant group is (Z/2)^2 for n even and Z/4 for n odd
    assert D_lat(n).dgroup[-2:] == ([2, 2] if n % 2 == 0 else [1, 4])


@pytest.mark.parametrize("n, det, nroots", [(4, 5, 20), (5, 4, 40), (6, 3, 72), (7, 2, 126), (8, 1, 240)])
def test_E(n, det, nroots):
    check_root_lattice(E_lat(n), n, det, nroots)
    if n < 8:  # E_lat_test(8) takes about 25 s to find its 240 roots
        check_root_lattice(E_lat_test(n), n, det, nroots)


@pytest.mark.parametrize("n", range(1, 7))
def test_B(n):
    # The root lattice of B_n is Z^n: 2n short roots of norm 1 and 2n(n - 1) long roots of norm 2
    L = B_lat(n)
    assert L.rank == n and L.signature == (n, 0) and L.parity and L.disc == 1
    assert norms(L, 2) == ({1: 2 * n, 2: 2 * n * (n - 1)} if n > 1 else {1: 2})


@pytest.mark.parametrize("n", range(1, 7))
def test_C(n):
    # The root lattice of C_n is D_n (spanned by the long roots ±2 e_i and the short ones ±e_i ± e_j);
    # C_1 = <4>
    L = C_lat(n)
    if n == 1:
        assert L.A.tolist() == [[4]]
    else:
        check_root_lattice(L, n, 4, 2 * n * (n - 1))


@pytest.mark.parametrize("n", [1, 2, 3, -1])
def test_U(n):
    L = U_lat(n)
    assert L.signature == (1, 1) and not L.parity and L.dgroup == [abs(n), abs(n)]
    assert L.square([1, 0]) == L.square([0, 1]) == 0


@pytest.mark.parametrize("p, q", [(1, 0), (3, 0), (0, 2), (1, 9), (2, 3)])
def test_I(p, q):
    L = I_lat(p, q)
    assert L.signature == (p, q) and L.parity and L.disc == 1
    assert L.A.tolist() == imat_diag([1] * p + [-1] * q).tolist()


@pytest.mark.parametrize("n", [1, 9, 17, 25])
def test_II(n):
    L = II_lat_n_1(n)
    assert L.rank == n + 1 and L.signature == (n, 1) and not L.parity and L.disc == 1


@pytest.mark.parametrize("make", [Leech_lat, Leech_lat_alt])
def test_leech(make):
    L = make()
    assert L.rank == 24 and L.signature == (24, 0) and not L.parity and L.disc == 1
    assert short_vectors(L, 2) == []


def test_leech_minimal_vectors():
    # The lattice is even without roots, so all the vectors with 0 < (v, v) <= 4 have norm 4
    L = Leech_lat_alt()
    A = np.array(L.A.tolist(), dtype=float)
    assert len(fp_search_cpp.FPSearch(A, np.zeros(24), 0.5, 4.5).search_all()) == 196560


@pytest.mark.parametrize("make, arg", [(A_lat, 0), (B_lat, 0), (C_lat, 0), (D_lat, 1), (E_lat, 3), (E_lat, 9),
                                       (E_lat_test, 3), (II_lat_n_1, 8)])
def test_invalid_rank(make, arg):
    with pytest.raises(ValueError):
        make(arg)


@pytest.mark.parametrize("p, q", [(0, 0), (3, -2), (-1, 2)])
def test_invalid_signature(p, q):
    with pytest.raises(ValueError):
        I_lat(p, q)

"""Tests of lattice.vinberg.quotient (the chamber modulo its symmetries, and the structure of Sym(C))."""
import copy
import flint as fl
import pytest
from lattice.lattice import Lattice
from lattice.catalogue import A_lat, D_lat, U_lat, I_lat
from lattice.vinberg.quotient import quotient_chamber, verify_quotient

pytest.importorskip("pynauty")

A2, D4, A3 = A_lat(2)(-1), D_lat(4)(-1), A_lat(3)(-1)
APOLLONIAN = lambda r: Lattice(r, [[1 - 2 * int(i == j) for j in range(r)] for i in range(r)])


@pytest.mark.parametrize("L, base, order, nwalls", [
    (U_lat() + A2 + A2 + A2, None, 6, 10),
    (I_lat(1, 9), [1] + [0] * 9, 1, 10),
    (Lattice(3, [[2, 1, 60], [1, -2, 0], [60, 0, -120]]), None, 2, 16),   # Allcock 104.11
    (U_lat() + A2 + A2 + A2 + A2 + A2, None, 240, 22),                     # a cusp A_2~^5: 243 edges, 21 orbits
])
def test_finite(L, base, order, nwalls):
    """Reflective lattices: the orbit of the walls at the representatives closes (all the walls of C), and the group
    generated by the identifications and the stabilizer is Sym(C) (the order of coxeter.symmetries)."""
    res = quotient_chamber(L, base=base)
    assert (res["structure"], res["reflective"], res["order"], res["walls"]) == ("finite", True, order, nwalls)
    assert verify_quotient(res["tracer"].certificate())["verified"] is True


def test_glue_graphs():
    """The finite vertices identified by their glue graphs (forced by max_orbit=0) instead of the orbits of their
    lattices."""
    res = quotient_chamber(U_lat() + D4 + D4 + D4, max_orbit=0)
    assert {r["local"].method for r in res["tracer"].representatives if not r["ideal"]} == {"glue"}
    assert (res["structure"], res["order"], res["walls"], res["representatives"]) == ("finite", 6, 17, 67)
    assert verify_quotient(res["tracer"].certificate(), max_orbit=0)["verified"] is True


def test_cusp_edges():
    """The edges at a cusp up to its stabilizer, without enumerating them: U + A_2(-1)^6 has a cusp A_1~^12 (4096
    edges) and a lattice Weyl vector of norm 0 (the heights are proportional to -(r, r) / 2)."""
    L = U_lat() + A2 + A2 + A2 + A2 + A2 + A2
    res = quotient_chamber(L, threads=2)
    assert res["structure"] == "parabolic" and res["heights"] == [(2, 1), (6, 3)] and res["Weyl vector"] is not None
    cusps = [r["local"] for r in res["tracer"].representatives if r["ideal"]]
    big = next(c for c in cusps if sorted(len(x) for x in c.comps) == [2] * 12)
    assert len(big.edges) < 4096 // 100


@pytest.mark.parametrize("L, heights", [
    (Lattice(1, [[14]]) + A3, [(2, 1), (2, 2), (4, 2)]),
    (APOLLONIAN(9), [(1, 2), (4, 0), (4, 2)]),
    (Lattice(9, [[1 - 7 * int(i == j) for j in range(9)] for i in range(9)]), [(14, 0), (14, 7), (14, 14)]),
])
def test_parabolic(L, heights, tmp_path):
    """Sym(C) fixes a cusp c (all its generators do): the heights (c, r) of all the walls, bounded and >= 0; the walls
    through c have rank < n - 1 (c is not a vertex of C, whose stabilizers are finite)."""
    path = str(tmp_path / "cert.json")
    res = quotient_chamber(L, certificate=path)
    assert res["structure"] == "parabolic" and res["reflective"] is False
    c = res["cusp"]
    assert L.square(c) == 0 and res["heights"] == heights and res["generalized Weyl vector"] is True
    assert res["rank of the walls through the cusp"] < L.rank - 1
    tracer = res["tracer"]
    assert all(list((fl.fmpz_mat([c]) * g).entries()) == c for g in tracer.generators + tracer.stabilizer)
    v = verify_quotient(path)
    assert v["verified"] is True and v["cusp"] == c


def test_cusps_identified():
    """Apollonian lattice of rank 10: the traversal closes only with the identification of the cusps."""
    res = quotient_chamber(APOLLONIAN(10), threads=2)
    assert res["structure"] == "parabolic" and res["cusps"] <= 5


@pytest.mark.parametrize("k, structure", [(7, "virtually cyclic"), (11, "virtually cyclic"), (19, "non-elementary")])
def test_hyperbolic(k, structure):
    """A hyperbolic element h: Sym(C) preserves its axis (virtually cyclic: <7> + A_3(-1), Salem of degree 4, and
    <11> + A_3(-1), quadratic) or not (non-elementary)."""
    res = quotient_chamber(Lattice(1, [[k]]) + A3)
    assert res["structure"] == structure and res["reflective"] is False
    if structure == "virtually cyclic":
        assert res["lambda"] > 1 and len(res["salem polynomial"]) == {7: 5, 11: 3}[k]
    assert verify_quotient(res["tracer"].certificate())["structure"] == structure


def test_tampering():
    """An identification with the wrong representative, a missing identification, or a wrong structure are rejected
    (a changed bijection of walls may still give a symmetry, which is then valid)."""
    cert = quotient_chamber(U_lat() + A2 + A2 + A2)["tracer"].certificate()
    verify_quotient(cert)
    bad = copy.deepcopy(cert)
    reps = bad["representatives"]
    ident = next(i for i in bad["identifications"] if not reps[i["target"]]["ideal"] and
                 i["end"] != reps[i["target"]]["vector"])
    ident["target"] = next(j for j, r in enumerate(reps) if not r["ideal"] and j != ident["target"] and
                           len(r["walls"]) == len(reps[ident["target"]]["walls"]))
    with pytest.raises(RuntimeError):
        verify_quotient(bad)
    bad = copy.deepcopy(cert)
    cusp = next(r for r in bad["representatives"] if r["ideal"] and r["transitions"])
    cusp["transitions"][0][2] = (cusp["transitions"][0][2] + 1) % len(cusp["edge orbits"])
    with pytest.raises(RuntimeError):
        verify_quotient(bad)
    bad = copy.deepcopy(cert)
    cusp = next(r for r in bad["representatives"] if r["ideal"] and r["transitions"])
    cusp["transitions"].pop()
    with pytest.raises(RuntimeError):
        verify_quotient(bad)
    bad = copy.deepcopy(cert)
    bad["identifications"].pop()
    with pytest.raises(RuntimeError):
        verify_quotient(bad)
    bad = copy.deepcopy(cert)
    bad["structure"]["structure"] = "parabolic"
    with pytest.raises(RuntimeError):
        verify_quotient(bad)

"""The chamber modulo its symmetries: a traversal of the 1-skeleton of C with one representative per orbit of
Sym(C), the generators of Sym(C) = O^+(L) / W(L), and certificates of its structure (finite, i.e. L reflective; parabolic:
Sym(C) fixes a cusp; virtually cyclic: Sym(C) preserves a geodesic; or non-elementary).

Principle. Two finite vertices of C are in the same Sym(C)-orbit iff an integral isometry maps one to the other with
the walls to the walls: by the orbit of the lattice Lambda_x under the automorphisms of the local diagram if they are
few (nonreflective.py), else by the canonical form of the glue graph of the vertex (_GlueFrame, with nauty; exact and
complete in both cases). The traversal keeps one representative per orbit and traces one edge per orbit of the
stabilizer of each representative: an end which is the image g(r) of a representative r gives the generator g (a
symmetry of C, by the local cones), otherwise it is a new representative. This terminates: Sym(C) has finitely many
orbits of vertices on C (a vertex of a chamber is cut out by simple roots of bounded norms, so it has a bounded norm,
and the positive vectors of bounded norm form finitely many O^+(L)-orbits; and two vertices of C in the same
O^+(L)-orbit are in the same Sym(C)-orbit, since the closure of C is a strict fundamental domain of W). Then, with H
generated by the identifications and the stabilizers of the representatives, H (representatives) is closed under
adjacency, hence the whole 1-skeleton; and since the representative r0 (the start) is in no other's orbit,
Sym(C) = H Stab(r0), and the walls at the representatives represent all its orbits of walls.

Cusps are handled through their edges (_CuspLocal): a symmetry of C is determined by its action near any edge, and
the framed edge (z, E), with the basis (E, z, z') (z' the other isotropic line of the plane of the edge), is a frame
like a finite vertex, with a glue graph. The orbits of Stab(z) on the edges at z (one dropped wall per component of
the affine diagram: up to 2^24 edges) are found by a search over the edges adjacent by a change in one component,
which also gives the generators of Stab(z); a cusp reached along an edge is identified by the key of that framed edge.

Structure (rigorous):
  - finite: the orbit of the walls at the representatives under the generators closes; then Sym(C) acts faithfully on
    this finite set (the walls span V), it is the set of all the walls of C, and L is reflective;
  - otherwise an element of infinite order is found (a generator, a product of two, or a nontrivial element of the
    kernel of the reduction modulo 3, which is torsion-free by Minkowski: from the Schreier generators of the image
    of the group in GL_n(F_3)); if it is parabolic with the cusp c and all the generators fix c, Sym(C) fixes c
    ("parabolic": Sym(C) is in the stabilizer of c, virtually Z^(n-2)); the heights (c, r) of the walls at the
    representatives are then the heights of all the walls (bounded: c is a generalized lattice Weyl vector if they are
    >= 0, a lattice Weyl vector up to scaling if proportional to -(r, r)/2);
  - a parabolic element with a generator not fixing its cusp: "non-elementary";
  - a hyperbolic element h: "virtually cyclic" if all the generators preserve its axis (Sym(C) is then in the
    stabilizer of the axis), else "non-elementary" (h and a conjugate have disjoint fixed points at infinity: a free
    subgroup); exact, by the rational hull ker f(h) of the axis, f the Salem factor (_axis).

verify_quotient checks a certificate: it retraces the traced edges of every representative, recomputes the
identifications, the orbits of edges at the finite representatives, the transitions between the edges at the cusps,
the inequivalence of r0 with the other representatives, its stabilizer, and the structure.
"""

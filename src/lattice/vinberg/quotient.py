def _identity(n: int) -> fl.fmpz_mat:
    return fl.fmpz_mat([[int(i == j) for j in range(n)] for i in range(n)])


def _as_int(M: fl.fmpq_mat) -> fl.fmpz_mat:
    if any(e.q != 1 for e in M.entries()):
        raise RuntimeError("Not an integral matrix")
    return fl.fmpz_mat([[int(M[i, j]) for j in range(M.ncols())] for i in range(M.nrows())])


class _QClass:
    """A representative r of a class of finite vertices (same norm, isomorphic local diagrams), with the orbit of
    Lambda_r under the automorphisms of its local diagram (key -> t with Lambda_r P_t = that lattice) and the Schreier
    generators of its stabilizer (the permutations sigma with Lambda_r P_sigma = Lambda_r)."""

    def __init__(self, r: _LocalVertex, rid: int, max_orbit: int):
        self.r, self.rid = r, rid
        k = r.k
        self.orbit: Dict[Tuple, List[int]] = {_lattice_key(r.Binv): list(range(k))}
        stab = set()
        frontier = [(r.Binv, list(range(k)))]
        gens = r.automorphisms()
        while frontier:
            new = []
            for C, t in frontier:
                for a in gens:
                    C2 = _permute_columns(C, a)
                    key = _lattice_key(C2)
                    ta = [a[t[i]] for i in range(k)]                       # first t, then a
                    if key not in self.orbit:
                        if len(self.orbit) >= max_orbit:
                            raise RuntimeError(f"The orbit of the lattice of a vertex exceeds {max_orbit}: its "
                                               f"identifications would not be complete")
                        self.orbit[key] = ta
                        new.append((C2, ta))
                    else:
                        u = self.orbit[key]
                        u_inv = [0] * k
                        for i, ui in enumerate(u):
                            u_inv[ui] = i
                        s = tuple(u_inv[ta[i]] for i in range(k))          # t a u^-1 fixes Lambda_r
                        if s != tuple(range(k)):
                            stab.add(s)
            frontier = new
        self.stabilizer = [list(s) for s in stab]

    def identify(self, x: _LocalVertex):
        """(g, sigma) with g an integral isometry mapping x to r and the wall i of x to the wall sigma[i] of r, or
        None."""
        if x.key != self.r.key:
            return None
        sigma0 = x.isomorphism_to(self.r)
        t = self.orbit.get(_lattice_key(_permute_columns(x.Binv, sigma0)))
        if t is None:
            return None
        t_inv = [0] * self.r.k
        for i, ti in enumerate(t):
            t_inv[ti] = i
        sigma = [t_inv[sigma0[i]] for i in range(x.k)]
        return _isometry(x, self.r, sigma), sigma

    def stabilizer_matrices(self) -> List[fl.fmpz_mat]:
        return [_isometry(self.r, self.r, s) for s in self.stabilizer]


def _isometry(x, r, sigma) -> fl.fmpz_mat:
    """g = B_x^-1 P_sigma B_r: the isometry mapping the wall i of x to the wall sigma[i] of r and the special vectors
    of x (the vertex, or the cusp and the other end of an edge) to those of r."""
    n = x.B.nrows()
    return _as_int(x.Binv * _permute_columns(fl.fmpq_mat([[int(i == j) for j in range(n)] for i in range(n)]), sigma)
                   * r.B)


def _canonical_hash(graph, label: List[int]) -> bytes:
    """A hash of the graph relabeled canonically (lab[t]: the vertex at the canonical position t); the coloring is
    part of the key separately. Equal hashes are confirmed by the integrality of the isometry they give."""
    pos = [0] * len(label)
    for t, v in enumerate(label):
        pos[v] = t
    edges = sorted(tuple(sorted((pos[u], pos[v]))) for u, vs in graph.adjacency_dict.items() for v in vs)
    return hashlib.sha256(repr(edges).encode()).digest()


def _glue_graph(L: Lattice, walls, specials, max_glue: int, diagram: WallDiagram = None):
    """(key, label, stabilizer) of the glue graph of the frame (walls, specials) (see _GlueFrame)."""
    k, t = len(walls), len(specials)
    n = k + t
    diagram = diagram if diagram is not None else WallDiagram(L, walls)
    Binv = fl.fmpq_mat([list(w) for w in walls] + [list(x) for x in specials]).inv()
    special_gram = tuple(L.product(list(x), list(y)) for i, x in enumerate(specials) for y in specials[i:])
    D = math.lcm(*[int(e.q) for e in Binv.entries()])
    # D Lambda (with D Z^n) in the coordinates (specials, walls): the HNF, whose first t rows project to the HNF of
    # the projection to the special coordinates (canonical), and whose other rows span its kernel
    order = list(range(k, n)) + list(range(k))
    H = fl.fmpz_mat([[int(Binv[i, j] * D) for j in order] for i in range(n)] +
                    [[D * int(i == j) for j in range(n)] for i in range(n)]).hnf()
    H = [[int(H[i, j]) for j in range(n)] for i in range(n)]
    zero = tuple([0] * k)
    Q = [i for i in range(t) if any(x % D for x in H[i][:t])]
    gens = {tuple(x % D for x in H[i][t:]) for i in range(t, n)} - {zero}
    K = {zero}
    frontier = [zero]
    while frontier:
        new = []
        for e in frontier:
            for g in gens:
                f = tuple((a + b) % D for a, b in zip(e, g))
                if f not in K:
                    if (len(Q) + 1) * len(K) >= max_glue:
                        raise RuntimeError(f"The glue graph of a vertex or an edge exceeds {max_glue} elements "
                                           f"(max_glue): its identifications would not be complete")
                    K.add(f)
                    new.append(f)
        frontier = new
    K = sorted(K)
    # The nodes: the nonzero elements of the kernel, then the fibres over the generators of the projection
    E = [(0, c) for c in K if c != zero]
    for j, i in enumerate(Q):
        lift = H[i][t:]
        E += sorted((j + 1, tuple((a + b) % D for a, b in zip(lift, c))) for c in K)
    G = diagram.gram
    values = sorted({G[i][j] for i in range(k) for j in range(i + 1, k)} - {0})
    code = {v: c + 1 for c, v in enumerate(values)}
    b = max(1, len(values).bit_length())
    vals = sorted({c[i] for _, c in E for i in range(k) if c[i]})
    code2 = {v: c + 1 for c, v in enumerate(vals)}
    b2 = max(1, len(vals).bit_length())
    off, ng = b * k, len(E)
    N = off + b2 * ng
    adj = {v: [] for v in range(N)}
    for i in range(k):
        for layer in range(b - 1):
            adj[i + layer * k].append(i + (layer + 1) * k)
        for j in range(i + 1, k):
            c = code.get(G[i][j], 0)
            for layer in range(b):
                if c >> layer & 1:
                    adj[i + layer * k].append(j + layer * k)
    for e, (_, c) in enumerate(E):
        for layer in range(b2 - 1):
            adj[off + e + layer * ng].append(off + e + (layer + 1) * ng)
        for i in range(k):
            if c[i]:
                for layer in range(b2):
                    if code2[c[i]] >> layer & 1:
                        adj[off + e + layer * ng].append(i)
    norms = diagram.norms()
    cells = []
    for layer in range(b):
        for d in sorted(set(norms)):
            cells.append({i + layer * k for i in range(k) if norms[i] == d})
    for layer in range(b2):
        for j in range(len(Q) + 1):
            cells.append({off + e + layer * ng for e in range(ng) if E[e][0] == j})
    cells = [c for c in cells if c]
    graph = pynauty.Graph(N, directed=False, adjacency_dict=adj, vertex_coloring=cells)
    label = pynauty.canon_label(graph)
    key = ("glue", special_gram, tuple(sorted(norms)), tuple(values), D, tuple(tuple(H[i][:t]) for i in range(t)),
           len(K), tuple(vals), tuple(len(c) for c in cells), _canonical_hash(graph, label))
    stabilizer = [list(p[:k]) for p in pynauty.autgrp(graph)[0] if list(p[:k]) != list(range(k))]
    return key, label, stabilizer


class _GlueFrame:
    """The glue graph of a frame: walls w_1, ..., w_k and special vectors s_1, ..., s_t with B = (walls, specials) a
    basis of V (a finite vertex: s = (x); an edge at a cusp: s = (z, z'), z' the other isotropic line of the plane
    of the edge). In the basis B, L has the coordinates Lambda = Z^n B^-1, and G = Lambda / Z^n = L / span(B) is a
    finite group (its elements as integer vectors modulo the exponent D). An isometry fixing the special vectors and
    permuting the walls by sigma, B^-1 P_sigma B, is integral iff P_sigma preserves G. G may be large (it contains
    the glue between the walls and their orthogonal complement: up to 2^24 elements at an edge of II_{1,25}), but it
    is an extension of the projection Q to the special coordinates (at most t generators, canonical: the HNF, and
    fixed by P_sigma) by the kernel K = (L cap span(walls)) / span(walls); P_sigma preserves G iff it preserves K and
    the fibres of G over the generators of Q. The graph has the walls (with the products as edge colors, as in
    WallDiagram.nauty_graph) and the elements of K - 0 and of these fibres (colored by the fibre), each joined to the
    walls where its coordinate is nonzero (colored by the coordinate, in the bits of layers of copies). Its
    automorphism group restricted to the walls is the stabilizer of the frame in O(L) (no orbit to enumerate), and
    two frames with the same products of the special vectors and the same Q are in the same O(L)-orbit iff their
    graphs are isomorphic (the canonical labelings give sigma). Such an isometry is a symmetry of C if the frames
    are vertices or edges of C (it maps the local cone of C to that of C). data: (key, label, stabilizer) computed
    elsewhere (in a worker)."""

    def __init__(self, L: Lattice, walls, specials, max_glue: int = None, diagram: WallDiagram = None, data=None):
        self.walls = [tuple(int(v) for v in w) for w in walls]
        self.specials = [tuple(int(v) for v in x) for x in specials]
        self.k = len(self.walls)
        self.B = fl.fmpq_mat([list(w) for w in self.walls] + [list(x) for x in self.specials])
        self.Binv = self.B.inv()
        if data is None:
            data = _glue_graph(L, self.walls, self.specials, max_glue, diagram)
        self.key, self.label, self.stabilizer = data

    def isomorphism_to(self, other: "_GlueFrame") -> List[int]:
        sigma = [0] * self.k
        for a, b in zip(self.label, other.label):
            if a < self.k:
                sigma[a] = b
        return sigma


class _FiniteLocal:
    """A finite vertex for the quotient traversal: identified by the orbit of its lattice (_QClass) if the
    automorphism group of its local diagram has at most max_orbit elements, else by its glue graph (_GlueFrame).
    As a representative, its stabilizer in Sym(C) as permutations of its walls, and as matrices. data: the
    canonical forms, computed elsewhere (in a worker: _finite_data)."""

    def __init__(self, L: Lattice, x, walls, max_orbit: int, max_glue: int, data=None):
        x, walls = tuple(int(v) for v in x), [tuple(int(v) for v in w) for w in walls]
        if data is None:
            self.lv = _LocalVertex(L, -1, x, walls)
            g = self.lv.diagram.nauty_graph("gram")
            self.lv.diagram.set_marked(g, (), "gram")
            _, s1, s2, _, _ = pynauty.autgrp(g)
            self.aut_order = round(s1 * 10 ** s2)
            glue = None if self.aut_order <= max_orbit else _glue_graph(L, walls, [x], max_glue, self.lv.diagram)
        else:
            canonical, self.aut_order, glue = data
            self.lv = _LocalVertex(L, -1, x, walls, canonical=canonical)
        self.x, self.walls, self.k = self.lv.x, self.lv.walls, self.lv.k
        self.max_orbit = max_orbit
        if glue is None:
            self.method, self.key, self.gv = "orbit", ("orbit",) + self.lv.key, None
        else:
            self.gv = _GlueFrame(L, walls, [x], data=glue)
            self.method, self.key = "glue", self.gv.key
        self.qclass = None

    def data(self):
        glue = None if self.gv is None else (self.gv.key, self.gv.label, self.gv.stabilizer)
        return (self.lv.key, self.lv.label), self.aut_order, glue

    def make_representative(self):
        if self.method == "orbit" and self.qclass is None:
            self.qclass = _QClass(self.lv, -1, self.max_orbit)
        return self

    def stabilizer_perms(self) -> List[List[int]]:
        return self.qclass.stabilizer if self.method == "orbit" else self.gv.stabilizer

    def stabilizer_matrices(self) -> List[fl.fmpz_mat]:
        base = self.lv if self.method == "orbit" else self.gv
        return [_isometry(base, base, s) for s in self.stabilizer_perms()]

    def identify(self, rep: "_FiniteLocal"):
        """(g, sigma): an integral isometry mapping this vertex to the representative rep (wall i to wall sigma[i]),
        or None."""
        if self.key != rep.key:
            return None
        if self.method == "orbit":
            return rep.qclass.identify(self.lv)
        sigma = self.gv.isomorphism_to(rep.gv)
        return _isometry(self.gv, rep.gv, sigma), sigma


def _orbits(n_items: int, perms) -> List[List[int]]:
    """The orbits of the items 0, ..., n_items - 1 under the group generated by the permutations (union-find)."""
    parent = list(range(n_items))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i
    for p in perms:
        for i in range(n_items):
            a, b = find(i), find(p[i])
            if a != b:
                parent[max(a, b)] = min(a, b)
    orbits: Dict[int, List[int]] = {}
    for i in range(n_items):
        orbits.setdefault(find(i), []).append(i)
    return sorted(orbits.values())


def _edge_orbits(local) -> List[List[int]]:
    """The orbits of the edges of a finite representative under its stabilizer (an edge is labeled by the wall it
    does not contain)."""
    return _orbits(local.k, local.stabilizer_perms())


def _other_end(L: Lattice, z, E) -> Tuple[int, ...]:
    """The other isotropic vector z' of the plane of the edge with walls E at the cusp z (primitive, (z, z') > 0)."""
    return _key(_cusp_direction(L, imat(list(z)), [imat(list(w)) for w in E], []))


def _edge_frame_data(L: Lattice, z, E, max_glue: int):
    """(z', the glue graph data) of the framed edge (z, E)."""
    zp = _other_end(L, z, E)
    return zp, _glue_graph(L, [tuple(w) for w in E], [tuple(z), zp], max_glue)


def _edge_frame(L: Lattice, z, E, max_glue: int = None, data=None) -> _GlueFrame:
    """The framed edge (z, E): the glue graph of the basis (E, z, z') (data: from _edge_frame_data)."""
    zp, glue = data if data is not None else _edge_frame_data(L, z, E, max_glue)
    return _GlueFrame(L, E, [z, zp], data=glue)


def _finite_data(L: Lattice, x, walls, max_orbit: int, max_glue: int):
    return _FiniteLocal(L, x, walls, max_orbit, max_glue).data()


def _local_task(kind, args):
    """A task of the quotient traversal in a worker (with the lattice of trace._init_worker): the canonical forms of
    a finite vertex ("finite") or of a framed edge ("edge frame")."""
    from lattice.vinberg import trace
    L = trace._WORKER["L"]
    return _finite_data(L, *args) if kind == "finite" else _edge_frame_data(L, *args)


def _frame_basis(L: Lattice, walls, specials):
    """The basis of a frame without its glue graph (for _isometry, in the verification)."""
    B = fl.fmpq_mat([list(w) for w in walls] + [list(x) for x in specials])
    return SimpleNamespace(k=len(walls), B=B, Binv=B.inv())


def _start_edge(walls, comps, E) -> Tuple[int, ...]:
    """The edge with the walls E at a cusp, as the tuple of the positions of the dropped walls (one per component)."""
    E = set(E)
    return tuple(next(i for i in comp if walls[i] not in E) for comp in comps)


class _CuspLocal:
    """A cusp z with the walls S (an affine diagram with the components comps) as a representative. Its edges drop
    one wall from each component (there may be very many: 2^24 at a cusp of type A_1~^24), and two edges are
    adjacent if they differ in one component. The orbits of Stab(z) (in Sym(C)) on the edges are found by a search
    over this graph from the edge start, by levels, with one representative edge per orbit: the framed edges (z, E)
    are identified by their glue graphs (_GlueFrame; an isometry between two of them fixes z and maps C to C).
    Stab(z) acts on the graph of the edges (connected), so it is generated by the stabilizers of the representative
    edges (nauty) and the transitions: elements mapping the neighbours of the representative edges to
    representatives (as for the traversal itself). Another cusp is identified with z through any of its edges, by
    the key of its framed edge (all the edges at z are in the orbits of the representative edges). frames(list of
    edge walls) -> their _edge_frame_data (in parallel, by the tracer); report(message): progress."""

    def __init__(self, L: Lattice, z, walls, comps, start, max_glue: int, max_edge_orbits: int, frames=None,
                 report=None):
        self.z, self.walls, self.comps = tuple(z), [tuple(w) for w in walls], [list(c) for c in comps]
        self.k = len(self.walls)
        self.edges: List[Tuple[int, ...]] = []    # the representative edges (dropped positions)
        self.frames: List[_GlueFrame] = []
        self.keys: Dict[Tuple, int] = {}          # key of a framed edge -> its representative edge
        self.transitions = []                      # (edge, dropped neighbour, its representative, sigma, g)
        if frames is None:
            frames = lambda Es: [_edge_frame_data(L, self.z, E, max_glue) for E in Es]
        computed: Dict[Tuple[int, ...], _GlueFrame] = {}

        def compute(ds):
            ds = [d for d in dict.fromkeys(ds) if d not in computed]
            for d, data in zip(ds, frames([self.edge_walls(d) for d in ds])):
                computed[d] = _edge_frame(L, self.z, self.edge_walls(d), data=data)

        def add(d):
            if len(self.edges) >= max_edge_orbits:
                raise RuntimeError(f"More than {max_edge_orbits} orbits of edges at the cusp {self.z} "
                                   f"(max_edge_orbits)")
            index[d] = len(self.edges)
            self.keys[computed[d].key] = len(self.edges)
            self.edges.append(d)
            self.frames.append(computed[d])

        def neighbours(d):
            return [d[:c] + (i,) + d[c + 1:] for c, comp in enumerate(self.comps) for i in comp if i != d[c]]
        index: Dict[Tuple[int, ...], int] = {}
        compute([tuple(start)])
        add(tuple(start))
        level = [0]
        while level:
            compute([d2 for j in level for d2 in neighbours(self.edges[j]) if d2 not in index])
            new = []
            for j in level:
                for d2 in neighbours(self.edges[j]):
                    if d2 in index:
                        continue
                    f = computed[d2]
                    t = self.keys.get(f.key)
                    if t is None:
                        new.append(len(self.edges))
                        add(d2)
                    else:
                        sigma = f.isomorphism_to(self.frames[t])
                        self.transitions.append((j, d2, t, sigma, _isometry(f, self.frames[t], sigma)))
            for d in [d for d in computed if d not in index]:
                del computed[d]
            level = new
            if report is not None:
                sizes = Counter(len(c) for c in comps)
                report(f"search at a cusp (components of sizes {' '.join(f'{m}^{sizes[m]}' for m in sorted(sizes))}):"
                       f" {len(self.edges)} orbits of edges, {len(self.transitions)} transitions")

    def edge_walls(self, d) -> List[Tuple[int, ...]]:
        return [self.walls[i] for i in range(self.k) if i not in d]

    def identify(self, f: _GlueFrame):
        """(t, sigma, g) with g an integral isometry mapping the framed edge f (at another cusp) to the representative
        edge t (wall i to wall sigma[i]), or None."""
        t = self.keys.get(f.key)
        if t is None:
            return None
        sigma = f.isomorphism_to(self.frames[t])
        return t, sigma, _isometry(f, self.frames[t], sigma)

    def stabilizer_matrices(self) -> List[fl.fmpz_mat]:
        one = _identity(len(self.z))
        gens = [g for *_, g in self.transitions] + [_isometry(f, f, s) for f in self.frames for s in f.stabilizer]
        return [g for g in gens if g != one]


class QuotientTracer:
    """Traces the chamber of L modulo its symmetries (see the module docstring). After run(): representatives (dicts
    with "vector", "walls", "ideal", "parent": (rep, edge walls) or None, "edges": the traced (walls, dropped walls),
    "local": _FiniteLocal or _CuspLocal), identifications (rep, edge walls, end vector, end walls, target rep, for a
    cusp its representative edge "orbit", sigma, matrix), generators and stabilizer (fmpz_mat, row action), and the
    result. Limits: max_orbit (the automorphisms of a local diagram for the orbit method, else the glue graph),
    max_glue (the glue nodes of a glue graph), max_edge_orbits (the orbits of edges at a cusp)."""

    def __init__(self, L: Lattice, base=None, chamber=None, seed: int = 0, threads: int = 1, cpp: bool = True,
                 max_representatives: int = 100000, max_orbit: int = 1000, max_glue: int = 20000,
                 max_edge_orbits: int = 100000):
        if pynauty is None:
            raise ImportError("The quotient traversal needs pynauty (pip install pynauty, or lattice[symmetry])")
        self.L, self.n = L, L.rank
        self.threads, self.cpp = threads, cpp
        self.max_representatives, self.max_orbit, self.max_glue = max_representatives, max_orbit, max_glue
        self.max_edge_orbits = max_edge_orbits
        start = ChamberTracer(L, base=base, chamber=chamber, seed=seed, threads=1, cpp=cpp)
        self.base, self._chamber, self._seed = start.base, chamber, seed
        v, walls, ideal = start._descend()
        self._start = (_key(v), [_key(w) for w in walls], ideal)

    def run(self, progress: bool = False, progress_interval: float = 10) -> dict:
        L, n = self.L, self.n
        t0 = last = time.perf_counter()
        gram = [[int(x) for x in row] for row in L.A.tolist()]
        executor = (ProcessPoolExecutor(max_workers=self.threads, initializer=_init_worker,
                                        initargs=(gram, None, self.cpp))
                    if self.threads > 1 else _InlineExecutor(gram, None, self.cpp))
        reps: List[dict] = []
        idents: List[dict] = []
        self.representatives, self.identifications = reps, idents   # also after an interruption
        classes: Dict[Tuple, List[int]] = {}         # key of a finite vertex -> representatives
        cusp_keys: Dict[Tuple, int] = {}             # key of a framed edge -> its cusp representative
        cusp_pending: Dict[Tuple[int, ...], list] = {}  # cusp -> the arrivals (rep, edge walls, frame) waiting for
        cusp_reps = set()                                 # its walls; the vectors of the cusp representatives
        known: Dict[Tuple[int, ...], None] = {}       # walls seen, to predict the ends of the edges
        queue: List[Tuple[int, int]] = []
        pending = {}
        window = 4 * max(self.threads, 1)

        def submit(kind, args, data):
            fn = _local_task if kind in ("finite", "edge frame") else _run_task
            pending[executor.submit(fn, kind, args)] = (kind, data)

        def report(message=None, force=False):
            nonlocal last
            now = time.perf_counter()
            if progress and (force or now - last >= progress_interval):
                last = now
                print(f"[{now - t0:.0f} s] {len(reps)} representatives ({sum(r['ideal'] for r in reps)} cusps), "
                      f"{len(idents)} identifications, {len(queue) + len(pending)} in the queue" +
                      (f"; {message}" if message else ""), flush=True)

        def frames_at(z):
            """The framed edges at z, computed in parallel by the workers."""
            def frames(Es):
                futures = [executor.submit(_local_task, "edge frame", (z, E, self.max_glue)) for E in Es]
                return [f.result() for f in futures]
            return frames

        def new_rep(vector, walls, ideal, parent, comps=None, start=None, local=None):
            if len(reps) >= self.max_representatives:
                raise RuntimeError(f"More than {self.max_representatives} representatives")
            rid = len(reps)
            S = [tuple(w) for w in walls]
            rep = {"vector": tuple(vector), "walls": S, "ideal": ideal, "parent": parent}
            reps.append(rep)
            for w in S:
                known.setdefault(w)
            if not ideal:
                local = local if local is not None else _FiniteLocal(L, rep["vector"], S, self.max_orbit,
                                                                      self.max_glue)
                rep["local"] = local.make_representative()
                classes.setdefault(local.key, []).append(rid)
                # One edge per orbit of the stabilizer (its elements are among the generators)
                rep["edges"] = [([S[i] for i in range(len(S)) if i != j], [S[j]])
                                for j in (orbit[0] for orbit in _edge_orbits(local))]
            else:
                local = _CuspLocal(L, rep["vector"], S, comps, start, self.max_glue, self.max_edge_orbits,
                                   frames=frames_at(rep["vector"]), report=report)
                rep["local"] = local
                for key, t in local.keys.items():
                    cusp_keys[key] = rid
                cusp_reps.add(rep["vector"])
                rep["edges"] = [(local.edge_walls(d), [S[i] for i in d]) for d in local.edges]
            queue.extend((rid, j) for j in range(len(rep["edges"])))
            report()
            return rid

        def arrive_finite(rid, E, end, walls, data):
            local = _FiniteLocal(L, end, walls, self.max_orbit, self.max_glue, data=data)
            for target in classes.get(local.key, []):
                found = local.identify(reps[target]["local"])
                if found is not None:
                    g, sigma = found
                    if tuple(end) == tuple(reps[target]["vector"]):
                        return   # the representative itself: g is in its stabilizer
                    idents.append({"rep": rid, "edge": [list(w) for w in E], "end": list(end),
                                   "end walls": [list(w) for w in local.walls], "target": target, "sigma": sigma,
                                   "matrix": g})
                    return
            new_rep(end, local.walls, False, (rid, [list(w) for w in E]), local=local)

        def arrive_cusp(rid, E, end, f=None) -> bool:
            """Identifies the cusp end, reached from rid along the edge E, by its framed edge; False if unknown."""
            if tuple(end) in cusp_reps:
                return True                              # the representative itself: g is in its stabilizer
            f = f if f is not None else _edge_frame(L, end, E, self.max_glue)
            target = cusp_keys.get(f.key)
            if target is None:
                return False
            t, sigma, g = reps[target]["local"].identify(f)
            idents.append({"rep": rid, "edge": [list(w) for w in E], "end": list(end),
                           "end walls": [list(w) for w in f.walls], "target": target, "orbit": t,
                           "sigma": sigma, "matrix": g})
            return True

        a, S, ideal = self._start
        report(f"start at a {'cusp' if ideal else 'finite vertex'} with {len(S)} walls", force=True)
        if ideal:
            comps = cusp_components(L, imat(list(a)), [imat(list(w)) for w in S])
            new_rep(a, S, True, None, comps=comps, start=tuple(c[0] for c in comps))
        else:
            new_rep(a, S, False, None)
        try:
            while queue or pending:
                while queue and len(pending) < window:
                    rid, j = queue.pop()
                    rep = reps[rid]
                    E, D = rep["edges"][j]
                    submit("edge", (rep["vector"], E, D, list(known)), (rid, E))
                if not pending:
                    break
                done, _ = wait(list(pending), return_when=FIRST_COMPLETED)
                for future in [f for f in pending if f in done]:
                    kind, data = pending.pop(future)
                    result = future.result()
                    if kind == "edge":
                        rid, E = data
                        end, ideal, alpha, _ = result
                        end = tuple(end)
                        if not ideal:
                            walls = E + [tuple(alpha)]
                            submit("finite", (end, walls, self.max_orbit, self.max_glue), (rid, E, end, walls))
                        elif end in cusp_pending:
                            cusp_pending[end].append((rid, E, None))
                        elif end not in cusp_reps:
                            submit("edge frame", (end, E, self.max_glue), (rid, E, end))
                    elif kind == "finite":
                        arrive_finite(*data, result)
                    elif kind == "edge frame":
                        rid, E, end = data
                        f = _edge_frame(L, end, E, data=result)
                        if end in cusp_pending:
                            cusp_pending[end].append((rid, E, f))
                        elif not arrive_cusp(rid, E, end, f):
                            a = reps[rid]["vector"]
                            m = a if not reps[rid]["ideal"] else tuple(x + y for x, y in zip(a, end))
                            cusp_pending[end] = [(rid, E, f)]
                            submit("cusp components", (end, E, m), end)
                    else:
                        end = data
                        walls, comps, _ = result
                        waiting = cusp_pending.pop(end)
                        rid, E, f = waiting[0]
                        # Another cusp of the same orbit may have become a representative in the meantime
                        if not arrive_cusp(rid, E, end, f):
                            walls = [tuple(w) for w in walls]
                            new_rep(end, walls, True, (rid, [list(w) for w in E]), comps=comps,
                                    start=_start_edge(walls, comps, E))
                        for rid, E, f in waiting[1:]:
                            if not arrive_cusp(rid, E, end, f):
                                raise RuntimeError(f"An edge at the cusp {end} is in no orbit of its representative")
                report()
        finally:
            executor.shutdown(wait=True, cancel_futures=True)
        self.representatives, self.identifications = reps, idents
        self.generators = [g for g in (i["matrix"] for i in idents) if g is not None and g != _identity(n)]
        # The stabilizers of all the representatives (needed with the edges traced up to them; that of r0 completes
        # the generators of Sym(C))
        self.stabilizer = [g for r in reps for g in r["local"].stabilizer_matrices()]
        report(f"traversal done; analysis of {len(self.generators) + len(self.stabilizer)} generators", force=True)
        self.result = analyze_quotient(L, self.generators + self.stabilizer,
                                       [w for r in reps for w in r["walls"]], self.base)
        self.result.update({"representatives": len(reps), "cusps": sum(r["ideal"] for r in reps),
                            "identifications": len(idents), "generators": len(self.generators) + len(self.stabilizer),
                            "seconds": round(time.perf_counter() - t0, 3)})
        if progress:
            print(f"[{self.result['seconds']:.0f} s] done: {len(reps)} representatives, structure "
                  f"{self.result['structure']}", flush=True)
        return self.result

    def certificate(self) -> dict:
        reps = self.representatives
        return {
            "format": CERTIFICATE_FORMAT,
            "gram": [[int(x) for x in row] for row in self.L.A.tolist()],
            "base": [int(x) for x in self.base],
            "chamber": [int(x) for x in self._chamber] if self._chamber is not None else None, "seed": self._seed,
            "representatives": [{"vector": list(r["vector"]), "walls": [list(w) for w in r["walls"]],
                                 "ideal": r["ideal"], "parent": r["parent"],
                                 "traced": [E for E, _ in r["edges"]],
                                 **({"edge orbits": [list(d) for d in r["local"].edges],
                                     "transitions": [[j, list(d), t, sigma] for j, d, t, sigma, _ in
                                                     r["local"].transitions]} if r["ideal"] else {})} for r in reps],
            "identifications": [{k: v for k, v in i.items() if k != "matrix"} for i in self.identifications],
            "structure": {k: v for k, v in self.result.items() if k in ("structure", "cusp", "word", "walls")},
        }


def _orbit_closure(walls, generators, max_size: int):
    """The orbit of the walls under the group generated by the matrices (row action), or None if it exceeds
    max_size."""
    seen = {tuple(int(x) for x in w) for w in walls}
    frontier = list(seen)
    while frontier:
        new = []
        for w in frontier:
            v = fl.fmpz_mat([list(w)])
            for g in generators:
                x = tuple(int(e) for e in (v * g).entries())
                if x not in seen:
                    if len(seen) >= max_size:
                        return None
                    seen.add(x)
                    new.append(x)
        frontier = new
    return sorted(seen)


def _infinite_generator(generators):
    """A generator of infinite order, as a word, or None."""
    for i, g in enumerate(generators):
        if has_infinite_order(g):
            return [(i, 1)]
    return None


def _infinite_element(n: int, generators, max_pairs: int = 30, max_image: int = 200000):
    """An element of infinite order of the group generated by the matrices, as a word [(i, +1 or -1)], or None: a
    product g h^-1 of two of the first max_pairs generators, or a nontrivial element of the kernel of the reduction
    modulo 3 (torsion-free, Minkowski) among the Schreier generators of the image in GL_n(F_3) (enumerated up to
    max_image elements)."""
    one = _identity(n)
    for i, g in enumerate(generators[:max_pairs]):
        for j in range(i):
            if has_infinite_order(g * _inverse(generators[j])):
                return [(i, 1), (j, -1)]
    def key(M):
        return bytes(int(e) % 3 for e in M.entries())
    elements = {key(one): (one, [])}
    frontier = [(one, [])]
    while frontier:
        new = []
        for M, word in frontier:
            for i, g in enumerate(generators):
                N, w2 = M * g, word + [(i, 1)]
                k = key(N)
                if k not in elements:
                    if len(elements) >= max_image:
                        return None
                    elements[k] = (N, w2)
                    new.append((N, w2))
                else:
                    T, wt = elements[k]
                    S = N * _inverse(T)                     # = 1 modulo 3
                    if S != one:
                        return w2 + [(i_, -e) for i_, e in reversed(wt)]
        frontier = new
    return None


def _evaluate(n: int, generators, word) -> fl.fmpz_mat:
    M = _identity(n)
    for i, e in word:
        M = M * (generators[i] if e == 1 else _inverse(generators[i]))
    return M


def _distinct(matrices) -> List[fl.fmpz_mat]:
    seen, out = set(), []
    for M in matrices:
        key = tuple(int(e) for e in M.entries())
        if key not in seen:
            seen.add(key)
            out.append(M)
    return out


def analyze_quotient(L: Lattice, generators, walls, base, max_walls: int = 50000) -> dict:
    """The structure of the group generated by the given symmetries of C (generating Sym(C)), from the walls at the
    representatives (see the module docstring). Order of the tests: a generator of infinite order (then the group is
    infinite), the orbit of the walls (finite: it closes), then products of generators and the reduction modulo 3."""
    n = L.rank
    generators = _distinct(generators)
    walls = sorted({tuple(int(x) for x in w) for w in walls})
    word = _infinite_generator(generators)
    orbit = _orbit_closure(walls, generators, max_walls) if word is None else None
    if orbit is not None:
        from sympy.combinatorics import Permutation, PermutationGroup
        index = {w: i for i, w in enumerate(orbit)}
        perms = [Permutation([index[tuple(int(e) for e in (fl.fmpz_mat([list(w)]) * g).entries())] for w in orbit])
                 for g in generators] or [Permutation(list(range(len(orbit))))]
        order = int(PermutationGroup(perms).order())
        return {"structure": "finite", "reflective": True, "order": order, "walls": len(orbit)}
    if word is None:
        word = _infinite_element(n, generators)
    if word is None:
        return {"structure": "undecided", "reflective": None}
    k, c = classify_element(L, _evaluate(n, generators, word))
    result = {"reflective": False, "word": [[int(i), int(e)] for i, e in word], "element": k}
    if k == "parabolic":
        b = [int(x) for x in base]
        if L.product(c, b) < 0:
            c = [-x for x in c]
        fixes = all(list((fl.fmpz_mat([c]) * g).entries()) == c for g in generators)
        result["structure"] = "parabolic" if fixes else "non-elementary"
        result["cusp"] = c
        if fixes:
            heights = sorted({(-L.square(list(w)), L.product(c, list(w))) for w in walls})
            result["heights"] = heights
            result["generalized Weyl vector"] = all(h >= 0 for _, h in heights)
            ratios = {fl.fmpq(h) / fl.fmpq(d, 2) for d, h in heights}
            result["Weyl vector"] = [x / next(iter(ratios)) for x in c] if len(ratios) == 1 and 0 not in ratios else None
            zero = [list(w) for w in walls if L.product(c, list(w)) == 0]
            result["rank of the walls through the cusp"] = fl.fmpz_mat(zero).rank() if zero else 0
    else:
        result.update(_axis(L, generators, _evaluate(n, generators, word), base))
    return result


def _axis(L: Lattice, generators, h: fl.fmpz_mat, base) -> dict:
    """Whether the generators preserve the axis of the hyperbolic element h (the geodesic between its isotropic
    eigenvectors v+, v- for the eigenvalues lambda, 1/lambda). With f the Salem factor of the characteristic
    polynomial of h (irreducible, simple), the rational hull of the axis is V_f = ker f(h), on which h^(+-1) has a
    single eigenline for lambda (v+, v-); so g preserves {v+, v-} iff g V_f = V_f and g^-1 h g = h^(+-1) on V_f (row
    action; the converse by the Galois conjugates of g v+ = c v+-). If all the generators do, Sym(C) is in the
    stabilizer of the axis, virtually cyclic (an extension of Z or D_infinity, "reverses": some generator swaps the
    ends, by a finite group); otherwise h and g^-1 h g have disjoint pairs of fixed points at infinity (a common one
    would contradict the discreteness), and Sym(C) contains a free group (ping-pong): non-elementary.
    In the virtually cyclic case, also "element": h (row action), and "axis": its endpoints, exactly: for a nonzero u
    in V_f and f = sum a_i x^i of degree d, v(mu) = u f(h) / (h - mu) = sum_j mu^j c_j with the integer vectors
    c_j = sum_k a_(k + j + 1) u h^k is an eigenvector for every root mu of f; "coefficients": [c_0, ..., c_(d-1)],
    "signs": [s+, s-] with v+ = s+ v(lambda), v- = s- v(1/lambda) future-directed, and "plus", "minus": v+, v-
    numerically, scaled to (v+, v-) = 1 (the axis is then {(e^t v+ + e^-t v-) / sqrt(2)}, of norm 1; h moves it by
    log lambda); "lattice": a basis of the saturated sublattice L cap V_f, of rank d and signature (1, d - 1): the
    rank-2 lattice of the plane of the axis if lambda is quadratic (d = 2), else its rational hull (the plane of the
    axis is then defined over Q(lambda + 1/lambda), not over Q)."""
    n = L.rank
    f = next(p for p, _ in h.charpoly().factor()[1] if p.is_cyclotomic() == 0)
    F = fl.fmpz_mat(n, n)
    for c in reversed(f.coeffs()):                       # Horner: F = f(h)
        F = F * h + int(c) * _identity(n)
    K, d = F.transpose().nullspace()
    K = fl.fmpz_mat([[int(K[i, j]) for i in range(n)] for j in range(d)])   # rows: a basis of V_f
    hK, hinvK = K * h, K * _inverse(h)
    reverses = False
    for i, g in enumerate(generators):
        conj = K * _inverse(g) * h * g
        if (K * g * F).is_zero() and conj in (hK, hinvK):
            reverses = reverses or (conj == hinvK)
        else:
            return {"structure": "non-elementary", "moves the axis": i}
    roots = [r for r, _ in fl.fmpz_poly(f.coeffs()).complex_roots()]
    lam = max(abs(complex(r)) for r in roots)
    a = [int(c) for c in f.coeffs()]
    d = len(a) - 1
    sub = Lattice.saturate(K.tolist())
    try:                                                  # a reduced basis, if the indefinite LLL succeeds
        _, T = Lattice(d, L.batch_prod(sub, sub)).lll(transform=True)
        sub = imat(T) @ sub
    except Exception:
        pass
    sub = [[int(x) for x in row] for row in sub]
    u = fl.fmpz_mat([sub[0]])
    powers = [u]
    for _ in range(d - 1):
        powers.append(powers[-1] * h)
    coefficients = [[sum(a[k + j + 1] * int(powers[k][0, i]) for k in range(d - j)) for i in range(n)]
                    for j in range(d)]
    A = np.array(L.A.tolist(), dtype=float)
    b = np.array([int(x) for x in base], dtype=float)
    v = [sum(mu ** j * np.array(c, dtype=float) for j, c in enumerate(coefficients)) for mu in (lam, 1 / lam)]
    signs = [1 if x @ A @ b > 0 else -1 for x in v]
    plus, minus = signs[0] * v[0], signs[1] * v[1]
    scale = math.sqrt(plus @ A @ minus)
    return {"structure": "virtually cyclic", "salem polynomial": a, "lambda": lam, "reverses": reverses,
            "element": [[int(h[i, j]) for j in range(n)] for i in range(n)],
            "axis": {"lattice": sub, "coefficients": coefficients, "signs": signs,
                     "plus": (plus / scale).tolist(), "minus": (minus / scale).tolist()}}


def quotient_chamber(L: Lattice, base=None, chamber=None, threads: int = 1, progress: bool = False,
                     certificate: str = None, **kwargs) -> dict:
    """Traces the chamber of L modulo Sym(C) and certifies the structure of Sym(C) (see the module docstring);
    returns the result of QuotientTracer.run() with the tracer under "tracer" (and saves the certificate)."""
    tracer = QuotientTracer(L, base=base, chamber=chamber, threads=threads, **kwargs)
    result = tracer.run(progress=progress)
    if certificate is not None:
        with open(certificate, "w") as f:
            json.dump(tracer.certificate(), f)
    result["tracer"] = tracer
    return result


# --- verification ---

def verify_quotient(cert: dict | str, cpp: bool = True, max_orbit: int = 1000, max_glue: int = 20000,
                    threads: int = 1) -> dict:
    """Checks a certificate of QuotientTracer (a dict or a JSON file): the walls at the root are those of a chamber C
    at it; the parent edges of the representatives, traced again, lead to them (so they are vertices of C); the edges
    traced at a finite representative represent the orbits of its stabilizer (recomputed, and added to the
    generators); at a cusp, every neighbour of a representative edge is mapped to a representative edge by the
    stated transition, an integral isometry fixing the cusp and its walls; every traced edge, traced again, ends at a
    representative or at the stated image of one by an integral isometry mapping the walls (at a cusp, the framed
    edge) to those of the representative; r0 is in no other representative's orbit; and the structure stated holds for
    the group generated by these symmetries and the stabilizer of r0 (recomputed). Returns the recomputed analysis
    (with "verified": True); raises RuntimeError otherwise. The edges are traced first, in threads processes (with
    the walls of the representatives to predict their ends, checked by the tracing)."""
    from lattice.vinberg.trace import _task_cusp
    if isinstance(cert, str):
        with open(cert) as f:
            cert = json.load(f)
    if cert.get("format") != CERTIFICATE_FORMAT:
        raise ValueError("Not a certificate of the quotient traversal")
    L = Lattice(len(cert["gram"]), cert["gram"])
    A = fl.fmpz_mat(cert["gram"])
    n = L.rank
    reps = cert["representatives"]
    tup = lambda v: tuple(int(x) for x in v)
    root = reps[0]
    if root["parent"] is not None:
        raise RuntimeError("The root has a parent")
    if root["ideal"]:
        # The walls at a root cusp: recomputed by the descent from the base point (as in the tracer)
        v, walls, ideal = ChamberTracer(L, base=cert["base"], chamber=cert["chamber"], seed=cert["seed"],
                                        cpp=cpp)._descend()
        if not ideal or tup(v) != tup(root["vector"]) or {tup(w) for w in walls} != {tup(w) for w in root["walls"]}:
            raise RuntimeError("The descent from the base point does not lead to the root cusp and its walls")
    elif not _local_walls_ok(L, root["vector"], root["walls"]):
        raise RuntimeError("The walls at the root are not those of a chamber at it")

    def edge(vector, walls, ideal, E):
        """The input of the tracing of the edge with the walls E at the vertex (checked to be an edge)."""
        S = [tup(w) for w in walls]
        E = [tup(w) for w in E]
        if not set(E) <= set(S):
            raise RuntimeError("An edge whose walls are not at the vertex")
        D = [w for w in S if w not in set(E)]
        a = tup(vector)
        if ideal:
            comps = cusp_components(L, imat(list(a)), [imat(list(w)) for w in S])
            if sorted(sum(S[i] in set(D) for i in comp) for comp in comps) != [1] * len(comps) or \
                    len(D) != len(comps):
                raise RuntimeError("Not an edge at a cusp")
        elif len(D) != 1:
            raise RuntimeError("Not an edge at a finite vertex")
        return a, tuple(E), tuple(D)

    # All the edges to trace: the parent edges and the traced edges of the representatives
    known = sorted({tup(w) for r in reps for w in r["walls"]})
    jobs = list(dict.fromkeys([edge(reps[r["parent"][0]]["vector"], reps[r["parent"][0]]["walls"],
                                    reps[r["parent"][0]]["ideal"], r["parent"][1]) for r in reps[1:]
                               if r["parent"] is not None and 0 <= r["parent"][0] < len(reps)] +
                              [edge(r["vector"], r["walls"], r["ideal"], E) for r in reps for E in r["traced"]]))
    gram = [[int(x) for x in row] for row in L.A.tolist()]
    executor = (ProcessPoolExecutor(max_workers=threads, initializer=_init_worker, initargs=(gram, None, cpp))
                if threads > 1 else _InlineExecutor(gram, None, cpp))
    try:
        futures = [executor.submit(_run_task, "edge", (a, list(E), list(D), known)) for a, E, D in jobs]
        traced_ends = {job: f.result()[:3] for job, f in zip(jobs, futures)}
    finally:
        executor.shutdown(wait=True, cancel_futures=True)

    def trace(vector, walls, ideal, E):
        """The end of the edge with the walls E at the vertex, whether it is a cusp, the walls at the end (at a
        cusp: those of the edge), and the point m from which the walls at a cusp are found."""
        a, E, D = edge(vector, walls, ideal, E)
        end, end_ideal, alpha = traced_ends[(a, E, D)]
        E = list(E)
        if end_ideal:
            return tup(end), True, E, a if not ideal else tuple(x + y for x, y in zip(a, end))
        return tup(end), False, E + [tup(alpha)], None

    def symmetry(g, walls, images):
        if g * A * g.transpose() != A:
            raise RuntimeError("An identification is not an isometry")
        if {tuple(int(e) for e in (fl.fmpz_mat([list(w)]) * g).entries()) for w in walls} != set(images):
            raise RuntimeError("An identification does not map the walls to the walls")
        return g

    def edge_basis(z, E):
        return _frame_basis(L, E, [z, _other_end(L, z, E)])

    # The representatives, from their parent edges (in order)
    for rid, r in enumerate(reps[1:], start=1):
        p, E = r["parent"]
        if not 0 <= p < rid:
            raise RuntimeError("A representative whose parent comes after it")
        end, ideal, walls, m = trace(reps[p]["vector"], reps[p]["walls"], reps[p]["ideal"], E)
        if ideal:
            walls = [tup(w) for w in _task_cusp(L, end, walls, m, cpp=cpp)[0]]
        if end != tup(r["vector"]) or ideal != r["ideal"] or set(walls) != {tup(w) for w in r["walls"]}:
            raise RuntimeError("A parent edge does not lead to its representative")
    index = {tup(r["vector"]): i for i, r in enumerate(reps)}
    locals_ = {i: _FiniteLocal(L, tup(r["vector"]), [tup(w) for w in r["walls"]], max_orbit,
                               max_glue).make_representative() for i, r in enumerate(reps) if not r["ideal"]}
    # The edges at the cusps: the representative edges (positions of the dropped walls, one per component)
    cusp_edges_of = {}
    for rid, r in enumerate(reps):
        if r["ideal"]:
            S = [tup(w) for w in r["walls"]]
            comps = cusp_components(L, imat(list(r["vector"])), [imat(list(w)) for w in S])
            comp_of = {i: c for c, comp in enumerate(comps) for i in comp}
            edges = [tuple(sorted(int(i) for i in d)) for d in r["edge orbits"]]
            if any(sorted(comp_of[i] for i in d) != list(range(len(comps))) for d in edges):
                raise RuntimeError("A representative edge at a cusp does not drop one wall per component")
            cusp_edges_of[rid] = (S, comps, edges)
    # The edges traced at each representative: one per orbit of its stabilizer (recomputed at a finite vertex; at a
    # cusp, the orbits are closed under adjacency by the transitions, each a symmetry fixing the cusp)
    stated = {(i["rep"], frozenset(tup(w) for w in i["edge"])): i for i in cert["identifications"]}
    generators = []
    for rid, r in enumerate(reps):
        S = [tup(w) for w in r["walls"]]
        z = tup(r["vector"])
        traced = [[tup(w) for w in E] for E in r["traced"]]
        if r["ideal"]:
            _, comps, edges = cusp_edges_of[rid]
            walls_of = lambda d: [S[i] for i in range(len(S)) if i not in d]
            if [set(E) for E in traced] != [set(walls_of(d)) for d in edges]:
                raise RuntimeError("The edges traced at a cusp are not its representative edges")
            position = {frozenset(d): j for j, d in enumerate(edges)}
            transitions = {(int(j), frozenset(int(i) for i in d)): (int(t), [int(x) for x in sigma])
                           for j, d, t, sigma in r["transitions"]}
            bases = {}
            basis = lambda d: bases.setdefault(d, edge_basis(z, walls_of(d)))
            for j, d in enumerate(edges):
                for comp in comps:
                    current = next(i for i in d if i in comp)
                    for i in comp:
                        d2 = frozenset(d) - {current} | {i}
                        if d2 in position:
                            continue
                        if (j, d2) not in transitions:
                            raise RuntimeError("A neighbour of a representative edge at a cusp is in no stated orbit")
                        t, sigma = transitions[(j, d2)]
                        g = symmetry(_isometry(basis(tuple(sorted(d2))), basis(edges[t]), sigma), S, S)
                        generators.append(g)
        else:
            local = locals_[rid]
            label = {frozenset([S[j]]): j for j in range(len(S))}
            orbit_of = {j: o for o, orbit in enumerate(_edge_orbits(local)) for j in orbit}
            hit = [orbit_of[label[frozenset(set(S) - set(E))]] for E in traced]
            if sorted(hit) != list(range(len(set(orbit_of.values())))):
                raise RuntimeError("The edges traced at a representative do not represent the orbits of its "
                                   "stabilizer")
            generators += local.stabilizer_matrices()
        for E in traced:
            end, ideal, walls, _ = trace(r["vector"], r["walls"], r["ideal"], E)
            if end in index:
                continue
            ident = stated.get((rid, frozenset(E)))
            if ident is None or tup(ident["end"]) != end or set(walls) != {tup(w) for w in ident["end walls"]}:
                raise RuntimeError("An edge of a representative ends neither at a representative nor at a stated image")
            target = int(ident["target"])
            if not 0 <= target < len(reps) or ideal != reps[target]["ideal"]:
                raise RuntimeError("An identification with a wrong representative")
            end_walls = [tup(w) for w in ident["end walls"]]
            if ideal:
                tS, _, tedges = cusp_edges_of[target]
                o = int(ident["orbit"])
                if not 0 <= o < len(tedges):
                    raise RuntimeError("An identification with a wrong representative edge")
                tE = [tS[i] for i in range(len(tS)) if i not in tedges[o]]
                g = _isometry(edge_basis(end, end_walls), edge_basis(tup(reps[target]["vector"]), tE), ident["sigma"])
                symmetry(g, end_walls, [tE[s] for s in ident["sigma"]])
            else:
                x = _LocalVertex(L, -1, end, end_walls)
                g = symmetry(_isometry(x, locals_[target].lv, ident["sigma"]), end_walls,
                             [tup(w) for w in reps[target]["walls"]])
            if g != _identity(n):
                generators.append(g)
    # r0 is in no other representative's orbit, and its whole stabilizer is among the generators
    if root["ideal"]:
        S, _, edges = cusp_edges_of[0]
        z = tup(root["vector"])
        frames = [_edge_frame(L, z, [S[i] for i in range(len(S)) if i not in d], max_glue) for d in edges]
        generators += [_isometry(f, f, s) for f in frames for s in f.stabilizer]
        keys = {f.key for f in frames}
        for i, (tS, _, tedges) in cusp_edges_of.items():
            if i != 0 and _edge_frame(L, tup(reps[i]["vector"]), [tS[j] for j in range(len(tS)) if j not in tedges[0]],
                                      max_glue).key in keys:
                raise RuntimeError("Two representatives are in the same orbit")
    else:
        r0 = locals_[0]
        if any(i != 0 and local.identify(r0) is not None for i, local in locals_.items()):
            raise RuntimeError("Two representatives are in the same orbit")
    result = analyze_quotient(L, generators, [tup(w) for r in reps for w in r["walls"]], reps[0]["vector"])
    claim = cert["structure"]
    if result["structure"] != claim["structure"] or (claim["structure"] == "parabolic" and
                                                     result["cusp"] != claim["cusp"]):
        raise RuntimeError(f"The structure stated ({claim['structure']}) is not the one found ({result['structure']})")
    result["verified"] = True
    return result

"""Certification of a candidate fundamental chamber of a reflective lattice.

Let walls be roots of a lattice L of signature (1, n) bounding a polyhedron P = {x : (x, w) >= 0} of
finite volume. If all walls are mirrors of the reflection group W of L, then P is a union of chambers
of W, and P is a single chamber iff no mirror of W meets the interior of P. If a mirror H does, then
H meets P in a polyhedron with a vertex, which is either a vertex of P or an interior point of an edge
of P. So P is a chamber iff
  (1) at every vertex a of P (finite or ideal), no mirror through a meets the interior of P near a,
  (2) no mirror meets an edge of P in an interior point.
For (1): the tangent cone of P at a is generated by the directions of the edges [a, b] at a, and a
mirror r^perp through a meets its interior iff (r, b) takes both signs on the adjacent vertices b.

The roots through a finite vertex a form a finite root system, found at height 0 of a search with base
point a. For an ideal vertex, they form finitely many classes (cusp_root_classes); in a class
r_t = w + t step, (r_t, b) is linear in t with slope of the sign of (step, b), so the mixed signs occur
for t in a bounded interval.

For (2): write r = r_Pi + r_N, where Pi is the plane of the edge [a, b] (of signature (1, 1)) and N
its orthogonal complement (negative definite). Then -2 exp(L) <= (r, r) <= (r_Pi, r_Pi) < 0. In the
basis a, b of Pi, with A = (r, a) > 0 > B = (r, b), p = (a, a), q = (b, b), c = (a, b) > 0:
    (r_Pi, r_Pi) = -(A^2 q + 2 A |B| c + B^2 p) / (c^2 - p q) >= -2 exp,
which bounds A, i.e. the height of r in a search with base point a:
  - a and b finite: A^2 <= 2 exp (c^2 - p q) / q;
  - a finite, b ideal: A <= exp c / div(b), since B is a nonzero multiple of div(b);
  - a and b ideal: A |B| <= exp c with A in div(a) Z, B in div(b) Z; the search uses the base point
    a + b, with |(r, a + b)| = |A - |B|| <= exp c / min(div(a), div(b)).
With method="height" (the reference implementation), all the roots up to these heights are listed by
VSearchCpp in vector mode (one search per finite vertex, covering the vertex check and the edges assigned to
it). With method="projection" (the default), the roots crossing each edge are found directly by
edge_crossing_roots (see lattice.vinberg.edges), which only enumerates the products ((r, a), (r, b)) in a
rank 2 lattice and short vectors of the complement of the edge, and the searches from the finite vertices
only cover height 0.
"""
from __future__ import annotations
import math
from fractions import Fraction
from typing import Iterator, List
import numpy as np
from lattice._matrix import IMat, imat, imat2flz, flq2imat
from lattice.lattice import Lattice
from lattice.roots import get_extremal_rays
from lattice.vinberg.algorithm import Vinberg, vsearch_cpp
from lattice.vinberg.walls import cusp_root_classes
from lattice.vinberg.edges import edge_crossing_roots


def _primitive(v) -> IMat:
    v = imat([int(x) for x in v])
    return v // math.gcd(*[int(x) for x in v])


def _matmul(X: np.ndarray, G: np.ndarray) -> np.ndarray:
    """X @ G for integer matrices, in int64 when this cannot overflow, else with Python integers."""
    if X.size == 0 or G.size == 0:
        return np.zeros((X.shape[0], G.shape[1]), dtype=np.int64)
    bound = int(np.abs(X).max()) * int(np.abs(G).max()) * X.shape[1]
    if bound < 2 ** 62:
        return X.astype(np.int64) @ G.astype(np.int64)
    return X.astype(object) @ G.astype(object)


def iter_roots(L: Lattice, base: IMat, height: int, threads: int = 1, chunk: int = 10 ** 6,
               batch: int = 10 ** 4) -> Iterator[np.ndarray]:
    """Streams all the roots r of L with 0 <= (r, base) <= height * div(base) (both signs at height 0), in
    batches: matrices whose rows are the roots in the coordinates of L. They are listed by VSearchCpp in
    vector mode from the base point base, (base, base) > 0, at most about chunk per batch."""
    V = Vinberg(L, base=base, h_batch=threads)
    B, _ = imat2flz(V.basis).inv().numer_denom()
    beta = (imat2flz(V.base) * B).tolist()[0]
    VS = vsearch_cpp.VSearchCpp(V.M.A.tolist(), beta, [0] * L.rank, 2 * V.M.exp + 0.5, threads, False, True)
    basis = np.array(V.basis.tolist(), dtype=object)
    while True:
        VS.run(chunk, batch)
        vecs = VS.get_vecs()
        if vecs:
            X = np.array(vecs, dtype=object)
            X = X[X[:, 0] <= height]
            if len(X):
                yield _matmul(X, basis)
        if VS.searched_height() >= height:
            break


def roots_by_height(L: Lattice, base: IMat, height: int, threads: int = 1) -> List[IMat]:
    """The roots of iter_roots() as a list of IMats (for small searches)."""
    return [imat([int(x) for x in r]) for X in iter_roots(L, base, height, threads) for r in X]


def certify_polytope(L: Lattice, walls: List[IMat] | List[List[int]], threads: int = 1, max_height: int = None,
                     verbose: bool = False, method: str = "projection") -> dict:
    """Checks whether the given roots of L (signature (1, n)) bound a fundamental chamber of the reflection
    group of L; see the module docstring for the method. The walls must be oriented so that the
    polyhedron is {x : (x, w) >= 0 for all walls w}. method is "projection" or "height" (the edge check;
    see the module docstring); max_height only applies to the searches of the method "height".

    Returns a dictionary with:
        certified: True if the walls bound a chamber, False if a violation was found, None if some search
            was skipped because its height exceeds max_height (and no violation was found);
        violations: a list of (kind, data, root): kind 'vertex' or 'cusp' (a mirror through the vertex data
            cuts P near it) or 'edge' (the mirror of root crosses the interior of the edge data = (a, b));
        heights: the list of (base point, height) of the searches; skipped: those not run;
        vertices, cusps, edges: the numbers of finite vertices, ideal vertices and edges of P."""
    walls = [imat([int(x) for x in w]) for w in walls]
    n = L.rank
    rays, lines = get_extremal_rays(walls, L.A)
    if len(lines) > 0:
        raise ValueError("The walls do not bound a pointed cone")
    rays = [_primitive(flq2imat(r)[0][0]) for r in rays]
    if any(L.square(r) < 0 for r in rays):
        raise ValueError("The polyhedron has infinite volume")
    if any(L.product(r, s) < 0 for r in rays for s in rays):
        raise ValueError("The extremal rays are not in one component of the light cone")
    tight = [{j for j, w in enumerate(walls) if L.product(r, w) == 0} for r in rays]
    # The edges: pairs of rays such that the walls through both have rank n - 2
    adj = {i: [] for i in range(len(rays))}
    edges = []
    for i in range(len(rays)):
        for j in range(i + 1, len(rays)):
            common = [walls[k] for k in tight[i] & tight[j]]
            if common and imat2flz(imat(common)).rank() == n - 2:
                adj[i].append(j)
                adj[j].append(i)
                edges.append((i, j))
    exp = L.exp
    div = [L.dual_vec(r)[1] for r in rays]
    finite = [i for i in range(len(rays)) if L.square(rays[i]) > 0]

    def bound(i, j):
        """The bound on (r, a) for the roots crossing the edge [a, b] = [rays[i], rays[j]], a finite."""
        p, q, c = L.square(rays[i]), L.square(rays[j]), L.product(rays[i], rays[j])
        if q > 0:
            return math.isqrt((2 * exp * (c * c - p * q)) // q)
        return (exp * c) // div[j]

    if method not in ("projection", "height"):
        raise ValueError("method must be 'projection' or 'height'")
    # Assign each edge with a finite endpoint to the endpoint needing the smaller height
    searches = {i: 0 for i in finite}
    assigned = {i: [] for i in finite}
    cusp_edges = []
    for i, j in (edges if method == "height" else []):
        options = [(bound(a, b) // div[a], a, b) for a, b in ((i, j), (j, i)) if a in searches]
        if not options:
            cusp_edges.append((i, j))
            continue
        h, a, b = min(options)
        searches[a] = max(searches[a], h)
        assigned[a].append(b)

    violations, heights, skipped = [], [], []

    def mixed(r, i):
        signs = {(L.product(r, rays[b]) > 0) - (L.product(r, rays[b]) < 0) for b in adj[i]}
        return 1 in signs and -1 in signs

    A_np = np.array(L.A.tolist(), dtype=object)
    for i in finite:
        a, h = rays[i], searches[i]
        if max_height is not None and h > max_height:
            skipped.append((a.tolist(), h))
            continue
        heights.append((a.tolist(), h))
        if verbose:
            print(f"Vertex {a.tolist()}: searching up to height {h}")
        # The products of the roots with a (column 0) and with the adjacent vertices
        G = A_np @ np.array([a.tolist()] + [rays[b].tolist() for b in adj[i]], dtype=object).T
        for X in iter_roots(L, a, h, threads):
            P = _matmul(X, G)
            at_a, others = P[:, 0], P[:, 1:]
            neg, pos = (others < 0).any(axis=1), (others > 0).any(axis=1)
            for k in np.nonzero((at_a == 0) & neg & pos)[0]:
                violations.append(('vertex', a.tolist(), [int(x) for x in X[k]]))
            # Any root with (r, a) > 0 > (r, b) crosses the edge [a, b]; the heights only ensure that all
            # the roots crossing the edges assigned to a are found
            for k in np.nonzero((at_a > 0) & neg)[0]:
                for col in np.nonzero(others[k] < 0)[0]:
                    violations.append(('edge', (a.tolist(), rays[adj[i][col]].tolist()), [int(x) for x in X[k]]))

    # Ideal vertices: the roots through a, class by class
    for i in range(len(rays)):
        if i in searches:
            continue
        a = rays[i]
        for w, step, m in cusp_root_classes(L, a):
            # (r_t, b) = (w, b) + t (step, b); the signs are mixed strictly between the extreme zeros
            zeros = [Fraction(-L.product(w, rays[b]), L.product(step, rays[b])) for b in adj[i]
                     if L.product(step, rays[b]) != 0]
            if len(zeros) < 2:
                continue
            for t in range(math.floor(min(zeros)), math.ceil(max(zeros)) + 1):
                r = w + t * step
                if L.is_root(r) and mixed(r, i):
                    violations.append(('cusp', a.tolist(), r.tolist()))

    # Edges between two ideal vertices: search from a + b
    for i, j in cusp_edges:
        a, b = rays[i], rays[j]
        y = a + b
        c = L.product(a, b)
        h = (exp * c // min(div[i], div[j])) // L.dual_vec(y)[1]
        if max_height is not None and h > max_height:
            skipped.append((y.tolist(), h))
            continue
        heights.append((y.tolist(), h))
        for r in roots_by_height(L, y, h, threads):
            if L.product(r, a) * L.product(r, b) < 0:
                violations.append(('edge', (a.tolist(), b.tolist()), r.tolist()))

    if method == "projection":
        for i, j in edges:
            for r, _ in edge_crossing_roots(L, rays[i], rays[j]):
                violations.append(('edge', (rays[i].tolist(), rays[j].tolist()), [int(x) for x in r]))

    certified = False if violations else (None if skipped else True)
    return {"certified": certified, "violations": violations, "heights": heights, "skipped": skipped,
            "vertices": len(finite), "cusps": len(rays) - len(finite), "edges": len(edges)}

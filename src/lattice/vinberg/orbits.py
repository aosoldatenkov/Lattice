"""Edge tracing up to symmetry: the chamber of a reflective lattice certified by tracing one vertex per orbit.

Let G be a group of isometries of L (integral, preserving the time orientation) permuting a set of known walls of
the chamber C, e.g. the symmetry group of the polyhedron of the walls found by a partial run of ChamberTracer
(coxeter.WallDiagram.symmetries). The traversal keeps one representative vertex per G-orbit, and traces all the
edges of the representatives (as in trace.py, with the same tasks). When an edge from a representative ends at a
vertex w, the walls of w are computed locally as usual; if they are the image g(walls of u) of those of a
representative u, g in G, then w = g(u) (a vertex is the intersection of its walls), and gC and C share the
vertex w and its local cone, so gC = C: each such identification certifies its own element g as a symmetry of C.
Otherwise w is a new representative.

Let H be the group generated by the certified elements (H is contained in Sym(C)). When the traversal ends, the set
H (representatives) is closed under adjacency: the edges at h(v) are the images under h of the edges at v, which
end at h g(u) for certified g. So it is the whole 1-skeleton of C, and the walls of C are the H-orbits of the walls
at the representatives. The numbers of vertices, cusps and edges follow by orbit-stabilizer in H. Nothing has to
be assumed about G: the certified H is usually all of G, and then G = Sym(C) if the known walls are all the walls.

Orbits are identified by enumerating G (practical up to a few million elements): the key of a set S of walls is the
smallest value over g in G of a 64-bit hash of g(S) (a sum of random values of its walls), with the ties broken by
the smallest image g(S) itself, so the key is exact. A wall outside the known ones at a traced vertex means that the
known walls are incomplete: it is added, the group is recomputed, and the traversal starts again.
"""
from __future__ import annotations
import json
import tempfile
import time
from concurrent.futures import ProcessPoolExecutor, wait, FIRST_COMPLETED
from typing import Dict, List, Sequence, Tuple
import numpy as np
from lattice._matrix import IMat, imat
from lattice.lattice import Lattice
from lattice.vinberg.coxeter import WallDiagram, ChamberSymmetry
from lattice.vinberg.trace import ChamberTracer, cusp_edges, load_walls, _key, _run_task, _init_worker, _InlineExecutor


class GroupAction:
    """A permutation group on k walls, enumerated from its generators: elements[i] is the array of the images of
    the walls under the i-th element (elements[0] is the identity). The elements are found by a breadth-first
    search over the words in the generators, vectorized; they are told apart by a 64-bit hash of the permutation
    (a collision would lose elements, which the comparison with the order of the group detects), and located by
    a binary search on the hashes (checked exactly)."""

    _CHUNK = 1 << 16

    def __init__(self, generators: Sequence[Sequence[int]], k: int, order: int = None, max_size: int = 2 * 10 ** 9,
                 seed: int = 0):
        self.k = k
        self.dtype = np.int16 if k < 2 ** 15 else np.int32
        rng = np.random.default_rng(seed)
        self._w = rng.integers(0, 2 ** 63, size=k, dtype=np.uint64) * np.uint64(2) + np.uint64(1)
        gens = [np.array(g, dtype=self.dtype) for g in generators]
        identity = np.arange(k, dtype=self.dtype)
        blocks, seen = [identity[None, :]], self._hash(identity[None, :])
        frontier = identity[None, :]
        size = 1
        while len(frontier) and gens:
            cand = np.concatenate([s[frontier] for s in gens])  # first the element, then s
            h = self._hash(cand)
            h, first = np.unique(h, return_index=True)
            new = ~np.isin(h, seen, assume_unique=True)
            frontier = cand[first[new]]
            size += len(frontier)
            if size * k * 10 > max_size:
                raise MemoryError(f"The group has more than {size} elements: too large to enumerate")
            blocks.append(frontier)
            seen = np.union1d(seen, h[new])
        self.elements = np.concatenate(blocks)
        self.order = len(self.elements)
        if order is not None and self.order != order:
            raise RuntimeError(f"Enumerated {self.order} elements of a group of order {order}")
        hashes = self._hash(self.elements)
        self._order_h = np.argsort(hashes)
        self._sorted_h = hashes[self._order_h]
        z = rng.integers(0, 2 ** 63, size=k, dtype=np.uint64) * np.uint64(2) + np.uint64(1)
        # Z[x, i] = z[elements[i][x]]: the hash of g_i(S) is the sum of the rows x in S (modulo 2^64)
        self._Z = np.ascontiguousarray(z[self.elements.T])

    def _hash(self, rows: np.ndarray) -> np.ndarray:
        out = np.empty(len(rows), dtype=np.uint64)
        for i in range(0, len(rows), self._CHUNK):
            out[i:i + self._CHUNK] = (rows[i:i + self._CHUNK].astype(np.uint64) * self._w).sum(axis=1, dtype=np.uint64)
        return out

    def indices(self, rows: np.ndarray) -> np.ndarray:
        """The positions in elements of the given elements (rows of images)."""
        rows = np.asarray(rows, dtype=self.dtype).reshape(-1, self.k)
        pos = np.searchsorted(self._sorted_h, self._hash(rows))
        pos = self._order_h[np.minimum(pos, self.order - 1)]
        if not (self.elements[pos] == rows).all():
            raise KeyError("Not an element of the group")
        return pos

    def index(self, perm) -> int:
        return int(self.indices(perm)[0])

    def canonical(self, S: Sequence[int]) -> Tuple[Tuple[int, ...], int]:
        """The canonical image of the set S of walls in its orbit (the smallest hash, then the smallest image) and
        the position of an element mapping S to it."""
        h = self._Z[list(S)].sum(axis=0, dtype=np.uint64)
        low = h.min()
        best = None
        for i in np.nonzero(h == low)[0]:
            image = tuple(sorted(int(x) for x in self.elements[i][list(S)]))
            if best is None or image < best[0]:
                best = (image, int(i))
        return best

    def stabilizer_mask(self, S: Sequence[int], mask: np.ndarray = None) -> int:
        """The number of elements (of the subgroup given by a boolean mask) mapping the set S to itself."""
        h = self._Z[list(S)].sum(axis=0, dtype=np.uint64)
        cand = np.nonzero((h == h[0]) & (mask if mask is not None else True))[0]
        S_sorted = sorted(S)
        return sum(1 for i in cand if sorted(int(x) for x in self.elements[i][list(S)]) == S_sorted)

    def extend(self, mask: np.ndarray, gens: List[int], new: int) -> np.ndarray:
        """The subgroup generated by the subgroup mask (generated by the elements at the positions gens) and the
        element at the position new, as a boolean mask; gens is extended by new. The words are extended on the
        right: first the members times the new generator, then the new elements times all the generators."""
        mask = mask.copy()
        mask[0] = True
        gens.append(new)
        gen_rows = [self.elements[g] for g in gens]
        frontier = np.nonzero(mask)[0]
        first = True
        while len(frontier):
            found = []
            for i in range(0, len(frontier), self._CHUNK):
                rows = self.elements[frontier[i:i + self._CHUNK]]
                for s in (gen_rows[-1:] if first else gen_rows):
                    idx = self.indices(s[rows])
                    idx = idx[~mask[idx]]
                    mask[idx] = True
                    found.append(idx)
            first = False
            frontier = np.unique(np.concatenate(found)) if found else np.array([], dtype=np.int64)
        return mask


class _NewWall(Exception):
    def __init__(self, wall):
        self.wall = wall


class OrbitTracer:
    """Traces and certifies the chamber of L up to the symmetries of the known walls (see the module docstring).
        walls: the known walls (e.g. those of a partial run); symmetry: their ChamberSymmetry (computed if None);
        base, chamber, seed: as for ChamberTracer, the start of the traversal (the start vertex must lie in the
            chamber of the known walls: pass those of the run which found them); threads, cpp, max_steps: as there.
    After run(), representatives lists the representative vertices: {"vector", "walls" (sorted indices in walls),
    "ideal", "degree" (number of edges), "orbit" (size of the H-orbit)}."""

    def __init__(self, L: Lattice, walls: Sequence, symmetry: ChamberSymmetry = None, base=None, chamber=None,
                 seed: int = 0, threads: int = 1, cpp: bool = True, max_steps: int = 200,
                 max_representatives: int = None):
        self.L = L
        self.n = L.rank
        self.threads = threads
        self.cpp = cpp
        self.max_steps = max_steps
        self.max_representatives = max_representatives
        start = ChamberTracer(L, base=base, chamber=chamber, seed=seed, threads=1, cpp=cpp, max_steps=max_steps)
        self.base = start.base
        # The start vertex, once (the descent chooses the chamber at the base point at random if it lies on mirrors)
        self._start = start._descend()
        self.restarts = 0
        self._set_walls(list(walls), symmetry)
        v = self._start[0]
        if any(L.product(v, w) < 0 for w in self.walls):
            raise ValueError("The start vertex is not on the positive side of the known walls: they are not walls of "
                             "its chamber (use the base, chamber and seed of the run which found them)")

    def _set_walls(self, walls, symmetry=None):
        self.diagram = WallDiagram(self.L, walls)
        self.walls = [imat(list(w)) for w in self.diagram.walls]
        self.wall_keys = list(self.diagram.walls)
        self.wall_index = dict(self.diagram.index)
        if symmetry is None:
            try:
                symmetry = self.diagram.symmetries(self.base)
            except ValueError:  # the walls do not span the space: no symmetries yet
                symmetry = ChamberSymmetry(len(self.walls), [], 1, 1)
        self.symmetry = symmetry
        self.group = GroupAction([s for s, _ in self.symmetry.generators], len(self.walls), self.symmetry.order)

    def _indices(self, walls) -> List[int]:
        idx = []
        for w in walls:
            k = _key(w)
            if k not in self.wall_index:
                raise _NewWall(k)
            idx.append(self.wall_index[k])
        return idx

    def run(self, progress: bool = False, progress_interval: float = 10) -> dict:
        """Traces the chamber up to symmetry; returns a summary (also stored in self.result). If a wall outside
        the known walls is met, it is added, the group is recomputed and the traversal restarts."""
        t0 = time.perf_counter()
        while True:
            try:
                result = self._run(progress, progress_interval, t0)
                break
            except _NewWall as e:
                self.restarts += 1
                if progress:
                    print(f"[{time.perf_counter() - t0:.0f} s] a new wall {e.wall}: {len(self.walls) + 1} walls, "
                          f"restarting with their symmetries", flush=True)
                self._set_walls(self.wall_keys + [e.wall])
        result["seconds"] = round(time.perf_counter() - t0, 3)
        result["restarts"] = self.restarts
        self.result = result
        if progress:
            print(f"[{result['seconds']:.0f} s] done: {result['walls']} walls, {result['vertices']} vertices, "
                  f"{result['cusps']} cusps, {result['edges']} edges; {result['orbits']} orbits of vertices; "
                  f"certified symmetries: order {result['certified_order']} of {result['group_order']}", flush=True)
        return result

    def _run(self, progress, progress_interval, t0) -> dict:
        L, G = self.L, self.group
        last = time.perf_counter()
        gram = [[int(x) for x in row] for row in L.A.tolist()]
        if self.threads > 1:
            executor = ProcessPoolExecutor(max_workers=self.threads, initializer=_init_worker,
                                           initargs=(gram, self.max_steps, self.cpp))
        else:
            executor = _InlineExecutor(gram, self.max_steps, self.cpp)
        reps: List[dict] = []
        rep_of: Dict[Tuple[int, ...], int] = {}  # canonical image -> representative
        canon_elt: List[int] = []                # for each representative, an element mapping it to its canonical image
        pending = {}
        queue: List[Tuple[int, int]] = []        # (representative, position of the edge)
        certified = set()                        # positions in G.elements of the certified elements
        H = np.zeros(G.order, dtype=bool)
        H[0] = True
        H_gens: List[int] = []
        traced = 0
        window = 4 * max(self.threads, 1)
        inverse = lambda a: np.argsort(a).astype(a.dtype)

        def submit(kind, args, data):
            pending[executor.submit(_run_task, kind, args)] = (kind, data, args)

        def failed(kind, args, error):
            fd, path = tempfile.mkstemp(prefix="trace_failure_", suffix=".json")
            with open(fd, "w") as f:
                json.dump({"kind": kind, "gram": gram, "exp": int(L.exp), "max_steps": self.max_steps,
                           "args": args, "error": repr(error)}, f)
            raise RuntimeError(f"{error} (in a {kind} task; its input is saved in {path})") from error

        def edges_of(S, ideal, drops):
            """The edges at a vertex with walls S (sorted indices): pairs (edge walls, dropped walls)."""
            if ideal:
                return [([w for w in S if w not in d], list(d)) for d in drops]
            return [([w for w in S if w != j], [j]) for j in S]

        def arrive(vector, S, ideal, drops):
            """A traced vertex with walls S: identified with a representative (certifying the element), or new."""
            nonlocal H
            S = sorted(S)
            image, e = G.canonical(S)
            if image in rep_of:
                u = rep_of[image]
                # e(S) = c_u(S_u): g = e^-1 c_u maps S_u to S
                g = inverse(G.elements[e])[G.elements[canon_elt[u]]]
                gi = G.index(g)
                if gi not in certified:
                    certified.add(gi)
                    if not H[gi]:
                        H = G.extend(H, H_gens, gi)
                return
            if self.max_representatives is not None and len(reps) >= self.max_representatives:
                raise RuntimeError(f"More than {self.max_representatives} orbits of vertices")
            rid = len(reps)
            rep = {"vector": tuple(int(x) for x in vector), "walls": tuple(S), "ideal": ideal,
                   "drops": [tuple(d) for d in drops] if ideal else None}
            rep["edges"] = edges_of(S, ideal, rep["drops"])
            rep["degree"] = len(rep["edges"])
            reps.append(rep)
            rep_of[image] = rid
            canon_elt.append(e)
            queue.extend((rid, j) for j in range(rep["degree"]))

        # The start vertex
        v, walls, ideal = self._start
        S = self._indices(walls)
        if ideal:
            drops = [tuple(S[i] for i in d) for d, _ in cusp_edges(L, v, walls)]
            arrive(_key(v), S, True, drops)
        else:
            arrive(_key(v), S, False, None)
        try:
            while queue or pending:
                while queue and len(pending) < window:
                    rid, j = queue.pop()
                    rep = reps[rid]
                    E, D = rep["edges"][j]
                    args = (rep["vector"], [self.wall_keys[i] for i in E], [self.wall_keys[i] for i in D],
                            list(self.wall_keys))
                    submit("edge", args, (rid, E))
                if not pending:
                    break
                done, _ = wait(list(pending), return_when=FIRST_COMPLETED)
                for future in done:
                    kind, data, args = pending.pop(future)
                    try:
                        result = future.result()
                    except Exception as e:
                        failed(kind, args, e)
                    if kind == "edge":
                        traced += 1
                        rid, E = data
                        end, ideal, alpha, _ = result
                        if ideal:
                            a = reps[rid]["vector"]
                            m = a if not reps[rid]["ideal"] else tuple(x + y for x, y in zip(a, end))
                            submit("cusp", (tuple(end), [self.wall_keys[i] for i in E], m), (tuple(end),))
                        else:
                            arrive(end, E + self._indices([alpha]), False, None)
                    else:
                        walls_z, drops_pos, _ = result
                        S = self._indices(walls_z)
                        arrive(data[0], S, True, [tuple(S[i] for i in d) for d in drops_pos])
                now = time.perf_counter()
                if progress and now - last >= progress_interval:
                    last = now
                    print(f"[{now - t0:.0f} s] {len(reps)} orbits of vertices ({sum(r['ideal'] for r in reps)} of "
                          f"cusps), {traced} edges traced, {len(queue) + len(pending)} in the queue; certified "
                          f"symmetries: order {int(H.sum())} of {G.order}", flush=True)
        finally:
            executor.shutdown(wait=True, cancel_futures=True)
        return self._summary(reps, H, traced)

    def _summary(self, reps, H, traced) -> dict:
        """The numbers of walls, vertices, cusps and edges of the chamber, from the H-orbits of the
        representatives (orbit-stabilizer)."""
        G = self.group
        order_H = int(H.sum())
        vertices = cusps = degree_sum = 0
        for rep in reps:
            stab = G.stabilizer_mask(rep["walls"], H)
            if order_H % stab:
                raise RuntimeError("The stabilizer of a representative does not divide the order of the group")
            rep["orbit"] = order_H // stab
            if rep["ideal"]:
                cusps += rep["orbit"]
            else:
                vertices += rep["orbit"]
            degree_sum += rep["orbit"] * rep["degree"]
        if degree_sum % 2:
            raise RuntimeError("The edges at the vertices do not pair up")
        # The walls of C: the H-orbits of the walls at the representatives
        at_reps = sorted({w for rep in reps for w in rep["walls"]})
        Hel = G.elements[H]
        wall_set = sorted({int(x) for x in np.unique(Hel[:, at_reps])})
        self.representatives = reps
        self.chamber_walls = [self.walls[i] for i in wall_set]
        return {"walls": len(wall_set), "known_walls": len(self.walls), "vertices": vertices, "cusps": cusps,
                "edges": degree_sum // 2, "orbits": len(reps), "traced": traced, "group_order": G.order,
                "certified_order": order_H, "chamber_walls": self.chamber_walls}


def trace_chamber_by_orbits(L: Lattice, walls: Sequence | str, base=None, chamber=None, progress: bool = False,
                            threads: int = 1, **kwargs) -> dict:
    """Certifies the chamber of L by tracing one vertex per orbit of the symmetries of the known walls (see the
    module docstring); returns the summary of OrbitTracer.run(), with the tracer under "tracer". walls is a list,
    or a file written by ChamberTracer(walls_file=...), whose base, chamber and seed are then used (unless given)."""
    if isinstance(walls, str):
        data = load_walls(walls)
        if data["gram"] != [[int(x) for x in row] for row in L.A.tolist()]:
            raise ValueError("The walls file is for another Gram matrix")
        walls = data["walls"]
        base = data["base"] if base is None else base
        chamber = data["chamber"] if chamber is None else chamber
        kwargs.setdefault("seed", data["seed"])
    tracer = OrbitTracer(L, walls, base=base, chamber=chamber, threads=threads, **kwargs)
    result = tracer.run(progress=progress)
    result["tracer"] = tracer
    return result

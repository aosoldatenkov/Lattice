"""Three-dimensional pictures of large Coxeter diagrams: a layout in R^3, rendered by WebGL in a self-contained
HTML page (no libraries, works offline).

For hundreds of walls a Coxeter diagram has tens or hundreds of thousands of edges (U + D_20: 210 walls, 16149 pairs
which are not orthogonal; Borcherds' lattice: 960 walls, 403296 pairs), beyond what SVG or TikZ can draw. Here the
nodes are point sprites and the edges indexed line buffers, one per kind of edge, which a GPU draws at once. The
kinds are colored rather than drawn as multiple lines: angles pi/3, pi/4, pi/6, parallel and ultraparallel pairs.

Layouts (layout3d):
    "stress": stress majorization on the shortest-path distances of the diagram (as in diagram.diagram_layout);
    "spectral": the eigenvectors of the smallest nonzero eigenvalues of the normalized Laplacian of the edges with an
        angle or parallel; the symmetries of the diagram act on its eigenspaces;
    "geometric": the walls seen from a point of the chamber fixed by the symmetries (see _geometric): each wall in
        the direction of its normal, at the distance of its mirror, projected to the principal 3-space.

The page: drag to rotate, wheel to zoom, shift-drag to pan; hover a wall for its root and norm; click a wall to show
its neighbours; a list of walls to highlight (e.g. the walls of a vertex); toggles and opacity for each kind of
edge; nodes colored by norm or by orbit of a symmetry group.
"""

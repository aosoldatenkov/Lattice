def _kind(label) -> str:
    if isinstance(label, Fraction):
        return "up"
    return {3: "a3", 4: "a4", 6: "a6", 'inf': "par"}[label]


def layout3d(k: int, labels: Dict, method: str = "stress", iterations: int = 300, seed: int = 0,
             diagram: WallDiagram = None, center=None, matrices=()) -> np.ndarray:
    """Positions in R^3 of the k nodes of a diagram with the given labels (see the module docstring), scaled so that
    the median length of the edges which are not ultraparallel is 1; the method "geometric" needs the diagram, and
    a center (a point of the closed chamber) and the matrices of its symmetries (see _geometric)."""
    if method == "stress":
        return diagram_layout(k, labels, iterations=iterations, dim=3, seed=seed)
    if k <= 1:
        return np.zeros((k, 3))
    if method == "spectral":
        # The normalized Laplacian I - D^-1/2 A D^-1/2 of the edges with an angle or parallel
        A = np.zeros((k, k))
        for (i, j), lab in labels.items():
            if not isinstance(lab, Fraction):
                A[i, j] = A[j, i] = 1.0
        d = A.sum(axis=1)
        d[d == 0] = 1.0
        Dm = 1.0 / np.sqrt(d)
        values, vectors = np.linalg.eigh(np.eye(k) - Dm[:, None] * A * Dm[None, :])
        X = (Dm[:, None] * vectors)[:, 1:4]
        return _normalize(X, labels)
    if method == "geometric":
        if diagram is None:
            raise ValueError("The geometric layout needs the walls (a WallDiagram)")
        return _normalize(_geometric(diagram, center, matrices, seed), labels)
    raise ValueError("method should be 'stress', 'spectral' or 'geometric'")


def _invariant_point(A: np.ndarray, x: np.ndarray, matrices: Sequence[np.ndarray]) -> np.ndarray:
    """The average of the orbit of x under the group generated by the matrices (row action x -> x M), without
    enumerating it: the projection of x to the fixed space V^G along U = sum of the images of M_i - I (V = V^G + U,
    and the average kills U). For x in a chamber preserved by the group, the result is in it (by convexity)."""
    n = len(x)
    if not matrices:
        return x
    D = np.hstack([M - np.eye(n) for M in matrices])           # x in V^G iff x D = 0
    _, sv, Vt = np.linalg.svd(D.T)
    rank = int((sv > 1e-9 * max(sv.max(), 1.0)).sum())
    F = Vt[rank:]                                               # rows: a basis of V^G
    U = np.vstack([M - np.eye(n) for M in matrices])            # rows span U
    _, su, Ut = np.linalg.svd(U)
    U = Ut[:int((su > 1e-9 * max(su.max(), 1.0)).sum())]
    coeffs = np.linalg.lstsq(np.vstack([F, U]).T, x, rcond=None)[0]
    return coeffs[:len(F)] @ F


def _geometric(diagram: WallDiagram, center=None, matrices=(), seed: int = 0) -> np.ndarray:
    """The walls seen from a point b of the chamber: each wall in the direction of its normal in b^perp (an
    orthonormal frame of the negative definite b^perp), at the distance from b to its mirror (plus a little, so that
    the walls through b stay apart), projected to the principal 3-space (slightly perturbed, generically: walls
    exchanged by a symmetry may have the same image in it). b is the average of the orbit of center (a point of the
    closed chamber, e.g. the base point of the tracing) under the symmetries given by their matrices, so that the
    picture is symmetric; without center, the least-squares solution of (b, r_i) = sqrt|(r_i, r_i)| (invariant too,
    but not always in the chamber)."""
    L = diagram.L
    A = np.array(L.A.tolist(), dtype=float)
    W = np.array(diagram.walls, dtype=float)
    norms = np.sqrt(np.abs(np.array([diagram.gram[i][i] for i in range(len(diagram))], dtype=float)))
    if center is not None:
        b = _invariant_point(A, np.array([float(x) for x in center]), [np.array(M, dtype=float) for M in matrices])
    else:
        b, *_ = np.linalg.lstsq(W @ A, norms, rcond=None)
    bb = b @ A @ b
    rb = W @ A @ b                                 # (r_i, b)
    if bb <= 0 or (rb < -1e-9 * np.abs(rb).max()).any():
        raise ValueError("The center is not a point of the chamber (pass center=, e.g. the base point of the tracing)")
    # An orthonormal frame of b^perp for -( , )
    _, _, Vt = np.linalg.svd((A @ b)[None, :])
    B = Vt[1:]                                     # a basis of b^perp (euclidean orthogonal to A b)
    C = np.linalg.cholesky(-(B @ A @ B.T))
    frame = np.linalg.solve(C, B)                  # rows orthonormal for -( , )
    u = W - np.outer(rb / bb, b)                   # the normals projected to b^perp
    coords = -(u @ A @ frame.T)
    coords /= np.linalg.norm(coords, axis=1, keepdims=True)
    dist = np.arcsinh(np.maximum(rb, 0) / (norms * np.sqrt(bb)))
    X = coords * (dist + 0.25 * max(float(np.median(dist)), 0.1))[:, None]
    X -= X.mean(axis=0)
    _, _, Vt = np.linalg.svd(X, full_matrices=False)
    P = Vt[:3] + 0.15 * np.random.default_rng(seed).standard_normal((3, len(Vt))) @ Vt
    Q, _ = np.linalg.qr(P.T)
    return X @ Q


class CoxeterDiagram3D:
    """The Coxeter diagram of the walls roots of L (a list, or a WallDiagram, e.g. tracer.diagram) with a layout in
    R^3; render with html(), or draw(path) for an .html file.
        symmetry: optional ChamberSymmetry of the walls: the nodes can be colored by its orbits, and the geometric
            layout is made symmetric with it; orbits: other orbits of the walls to color the nodes by;
        method: the layout (see layout3d), or layout: given positions (k x 3); center: a point of the closed chamber
            for the geometric layout (e.g. the base point of the tracing)."""

    def __init__(self, L: Lattice, roots: Sequence | WallDiagram, method: str = "stress", layout: np.ndarray = None,
                 symmetry=None, orbits: Sequence[Sequence[int]] = None, center=None, iterations: int = 300,
                 seed: int = 0):
        diagram = roots if isinstance(roots, WallDiagram) else WallDiagram(L, roots)
        self.roots = [list(r) for r in diagram.walls]
        self.k = len(self.roots)
        self.norms = diagram.norms()
        self.labels = diagram.labels()
        if orbits is None and symmetry is not None:
            orbits = symmetry.wall_orbits
        self.orbits = [sorted(o) for o in orbits] if orbits is not None else None
        matrices = [np.array(M.tolist(), dtype=float) for _, M in symmetry.generators] if symmetry is not None else ()
        self.xyz = (np.asarray(layout, dtype=float) if layout is not None
                    else layout3d(self.k, self.labels, method, iterations, seed, diagram=diagram, center=center,
                                  matrices=matrices))

    def _data(self, highlight: Sequence[int]) -> Dict:
        def b64(a: np.ndarray) -> str:
            return base64.b64encode(np.ascontiguousarray(a).tobytes()).decode("ascii")
        index_type = np.uint16 if self.k < 2 ** 16 else np.uint32
        edges = {key: [] for key, _, _ in _KINDS}
        for (i, j), lab in self.labels.items():
            edges[_kind(lab)].extend((i, j))
        norm_values = sorted(set(self.norms))
        color_norm = [norm_values.index(d) for d in self.norms]
        if self.orbits is not None:
            orbit_of = [0] * self.k
            for c, o in enumerate(sorted(self.orbits, key=len, reverse=True)):
                for w in o:
                    orbit_of[w] = c
        return {
            "k": self.k,
            "pos": b64(self.xyz.astype(np.float32)),
            "index32": index_type == np.uint32,
            "edges": {key: b64(np.array(v, dtype=index_type)) for key, v in edges.items()},
            "counts": {key: len(v) // 2 for key, v in edges.items()},
            "kinds": [{"key": key, "name": name, "color": color} for key, name, color in _KINDS],
            "palette": _COLORS,
            "byNorm": {"classes": color_norm, "legend": [f"(r, r) = {-d}" for d in norm_values]},
            "byOrbit": None if self.orbits is None else {
                "classes": orbit_of,
                "legend": [f"orbit of {len(o)}" for o in sorted(self.orbits, key=len, reverse=True)]},
            "titles": [f"wall {i}: r = {tuple(self.roots[i])}, (r, r) = {-self.norms[i]}" for i in range(self.k)],
            "highlight": [int(i) for i in highlight],
        }

    def html(self, title: str = "Coxeter diagram", highlight: Sequence[int] = (), ultraparallel: bool = None) -> str:
        """A self-contained HTML page rendering the diagram with WebGL (see the module docstring)."""
        data = self._data(highlight)
        if ultraparallel is None:
            ultraparallel = data["counts"]["up"] <= 20000
        data["show"] = {key: (key != "up" or ultraparallel) for key, _, _ in _KINDS}
        summary = (f"{self.k} walls; " + ", ".join(f"{data['counts'][key]} {name}" for key, name, _ in _KINDS
                                                   if data["counts"][key]))
        page = _HTML.replace("__TITLE__", html.escape(title)).replace("__SUMMARY__", html.escape(summary))
        return page.replace("__DATA__", json.dumps(data))

    def draw(self, path: str, **kwargs) -> str:
        if os.path.splitext(path)[1].lower() != ".html":
            raise ValueError("The 3D picture is an .html page")
        with open(path, "w", encoding="utf-8") as f:
            f.write(self.html(**kwargs))
        return path


def draw_Coxeter_diagram_3d(L: Lattice, roots: Sequence | WallDiagram, path: str, method: str = "stress",
                            symmetry=None, center=None, **kwargs) -> CoxeterDiagram3D:
    """Computes the 3D layout of the Coxeter diagram of the walls roots of L and writes the WebGL page to path;
    returns the diagram, to render it again."""
    diagram = CoxeterDiagram3D(L, roots, method=method, symmetry=symmetry, center=center)
    diagram.draw(path, **kwargs)
    return diagram



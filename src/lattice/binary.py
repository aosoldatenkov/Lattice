"""Binary lattices: integral symmetric bilinear forms on Z^2.

Conventions
-----------
A binary lattice is Z^2 with the symmetric bilinear form

    (u, v) = a u0 v0 + h (u0 v1 + u1 v0) + b u1 v1,

i.e. with Gram matrix A = [[a, h], [h, b]] in the standard basis. Vectors are coordinate
pairs (x, y) in the standard basis, used as row vectors: (u, v) = u A v^T. The norm of v is
(v, v) = a x^2 + 2h xy + b y^2; we always work with norms of the bilinear form, never with
the quadratic form (v, v) / 2. The lattice is even if all norms are even (a, b even).
Isomorphism means equivalence under GL_2(Z), i.e. orientation-reversing changes of basis
are allowed. Oriented isomorphism (equivalence under SL_2(Z), the classical equivalence of
binary quadratic forms) is available via is_isomorphic(other, oriented=True). The two notions
agree exactly when the lattice has an automorphism of determinant -1
(see BinLattice.improper_automorphism); for quadratic forms these are the ambiguous classes.

The algorithms follow Conway's topograph (J. H. Conway, "The Sensual (Quadratic) Form"),
applied to the norm v -> (v, v). Primitive vectors up to sign are the regions of the
topograph, a basis (e, f) is an edge, and a superbase {e, f, -(e + f)} is a vertex.

- Definite lattices have a "well": an obtuse superbase, whose three norms are the smallest
  ones (up to sign of the form).
- Indefinite lattices have a "river" of edges (e, f) with (e, e) > 0 > (f, f), separating
  positive and negative norms. The river is periodic, unless the lattice represents zero;
  then it runs between two "lakes" (primitive isotropic vectors). If both vectors of a
  basis are isotropic (the lattice is U(h)), there is no river.
- Climbing lemma: away from the well or the river the absolute values of the norms grow,
  so all norms up to a bound can be listed by exploring finitely many branches of the
  topograph tree, starting from "seed" edges next to the well or the river.
"""
import math
import operator
from collections import defaultdict
from dataclasses import dataclass
from fractions import Fraction
from typing import Tuple, List, Optional, Dict, Set, Any
from sympy import Matrix, ZZ, factorint, multiplicity
from sympy.matrices.normalforms import smith_normal_decomp
from lattice._matrix import IMat, imat, inv2x2

@dataclass
class BinBasis:
    """A pair of vectors (e, f) with its Gram data a = (e, e), b = (f, f), h = (e, f).

    Represents an edge of the topograph. The methods returning new bases keep (a, b, h)
    consistent with (e, f), except negate(), which changes the form instead (see below).
    """
    e: Tuple[Any, Any]
    f: Tuple[Any, Any]
    a: Any
    b: Any
    h: Any

    def __lt__(self, other: 'BinBasis') -> bool:
        """Compares lexicographically by (|h|, |a|, |b|). Used to choose a canonical basis
        among the finitely many edges of a river (or its two ends)."""
        for attr in ('h', 'a', 'b'):
            diff = abs(getattr(self, attr)) - abs(getattr(other, attr))
            if diff != 0:
                return diff < 0
        return False

    def flip(self) -> 'BinBasis':
        """The basis (e, -f), with Gram data (a, b, -h). Reverses the orientation; on a river,
        it reverses the direction of the flow."""
        return BinBasis(self.e, (-self.f[0], -self.f[1]), self.a, self.b, -self.h)

    def swap(self) -> 'BinBasis':
        """The basis (f, e), with Gram data (b, a, h)."""
        return BinBasis(self.f, self.e, self.b, self.a, self.h)

    def negate(self) -> 'BinBasis':
        """The same vectors with Gram data (-a, -b, -h), i.e. the basis of the lattice L(-1)."""
        return BinBasis(self.e, self.f, -self.a, -self.b, -self.h)

    def copy(self) -> 'BinBasis':
        return BinBasis(self.e, self.f, self.a, self.b, self.h)

    def sum(self) -> Tuple[Any, Any]:
        """The vector e + f, the third vector of the superbase {e, f, -(e + f)} up to sign."""
        return (self.e[0] + self.f[0], self.e[1] + self.f[1])

    def imat(self) -> IMat:
        """The 2x2 matrix with rows e and f."""
        return imat([self.e, self.f])


@dataclass
class BinDiscForm:
    """The discriminant form of a nondegenerate integral binary lattice L.

    The group L^*/L = Z/d1 x Z/d2 (d1 | d2) is generated by g1, g2 in L^* (rational vectors in
    the standard coordinates of L), of orders d1, d2. Elements are coordinate pairs (i, j),
    meaning i g1 + j g2, with i mod d1 and j mod d2. The form is given by q1 = (g1, g1),
    q2 = (g2, g2) mod `mod` and b = (g1, g2) mod 1. For an even lattice mod = 2 and q is the
    discriminant quadratic form with values in Q/2Z; for an odd lattice only (x, x) mod Z is
    well defined, so mod = 1.
    """
    orders: Tuple[int, int]
    gens: Tuple[Tuple[Fraction, Fraction], Tuple[Fraction, Fraction]]
    q1: Fraction
    q2: Fraction
    b: Fraction
    mod: int

    def value(self, x: Tuple[int, int]) -> Fraction:
        """q(x) = (x, x) mod `mod`, for x = (i, j)."""
        i, j = x
        return (i * i * self.q1 + 2 * i * j * self.b + j * j * self.q2) % self.mod

    def bilinear(self, x: Tuple[int, int], y: Tuple[int, int]) -> Fraction:
        """b(x, y) = (x, y) mod 1."""
        return (x[0] * y[0] * self.q1 + (x[0] * y[1] + x[1] * y[0]) * self.b + x[1] * y[1] * self.q2) % 1

    def is_isomorphic(self, other: 'BinDiscForm') -> bool:
        """Checks whether there is a group isomorphism preserving q (and hence b).

        The forms split orthogonally into p-parts, so it suffices to compare these. The p-part
        Z/p^s x Z/p^t (s <= t) is generated by u1 = (d1 / p^s) g1 and u2 = (d2 / p^t) g2. An
        isomorphism is given by images y1, y2 in the p-part of other with p^s y1 = 0,
        q(y1) = q(u1), q(y2) = q(u2), b(y1, y2) = b(u1, u2), which generate it. By Burnside's
        basis theorem, they generate iff their images in A_p / p A_p are linearly independent.
        """
        if (self.mod, self.orders) != (other.mod, other.orders):
            return False
        d1, d2 = self.orders
        for p in factorint(d2):
            s, t = multiplicity(p, d1), multiplicity(p, d2)
            c1, c2 = d1 // p**s, d2 // p**t
            u1, u2 = (c1, 0), (0, c2)
            # Elements of the p-part of other, with their coordinates (i, j) w.r.t. its generators
            elems = [((i, j), (c1 * i, c2 * j)) for i in range(p**s) for j in range(p**t)]
            Y1 = [(ij, y) for ij, y in elems if (p**s * ij[1]) % p**t == 0 and other.value(y) == self.value(u1)]
            Y2 = [(ij, y) for ij, y in elems if other.value(y) == self.value(u2)]
            target = self.bilinear(u1, u2)
            if not any(other.bilinear(y1, y2) == target and
                       ((i1 * j2 - j1 * i2) % p != 0 if s > 0 else j2 % p != 0)
                       for (i1, j1), y1 in Y1 for (i2, j2), y2 in Y2):
                return False
        return True


class BinLattice:
    """The binary lattice with Gram matrix [[a, h], [h, b]].

    The constructor computes the invariants and the topograph data:

    disc       |det| = |a b - h^2|, as Lattice.disc.
    exp        disc / gcd(a, b, h), the exponent of the discriminant group (0 for degenerate
               lattices). None if a, b or h is not an integer: the discriminant group is only
               defined for integral lattices.
    signature  (n_+, n_-), counting nonzero eigenvalues only: (0, 0) for the zero form,
               (1, 0) or (0, 1) for degenerate nonzero forms.
    parity     0 if even, 1 if odd, None if a, b or h is not an integer.
    can        the canonical basis, a BinBasis. Its Gram data (can.a, can.b, can.h)
               is a complete isomorphism invariant (together with the signature):
               - definite: the well, |a| <= |b| <= |a + b + 2h|, h <= 0 for positive
                 and h >= 0 for negative definite lattices;
               - indefinite with a periodic river: the smallest edge of the river with
                 respect to BinBasis.__lt__, flipped so that h > 0;
               - indefinite representing zero: the smaller of the two end edges of the
                 river, oriented to flow towards the other end; U(h) gives (0, 0, h), h > 0;
               - degenerate: (0, m, 0), where e spans the kernel and m is the norm of f;
               - zero form: the standard basis, (0, 0, 0).
    zero       the primitive isotropic vectors, both signs: the kernel for degenerate
               lattices, the two isotropic lines for indefinite lattices representing zero,
               empty otherwise (also for the zero form, where every vector is isotropic).
    river      indefinite lattices: the edges of the river starting at can, one full period
               (periodic river) or from one lake to the other. Empty otherwise. Its length is
               the sum of the partial quotients of a continued fraction, which can be of order
               sqrt(disc) (e.g. 4n for x^2 - (n^2 + 1) y^2); the constructor stores the river
               edge by edge, so indefinite lattices with huge disc may be slow or run out of
               memory. Reaching the river (descend) is fast for any entries.
    shift      periodic river: the 2x2 matrix S of the automorphism moving the river by one
               period in the direction of river: can S is the edge following river[-1]. It acts
               on row vectors, v -> v S; det S = 1 and S A S^T = A. Together with -1 it
               generates the group of proper automorphisms. None otherwise.
    pos, neg   seed edges (e, f) for list_positive / list_negative: edges of nonnegative
               (resp. nonpositive) vectors next to the well, the river or the lakes,
               oriented so that h >= 0 (resp. h <= 0), so that the norm of e + f grows
               (resp. decreases).
    """
    def __init__(self, a: Any, b: Any, h: Any):
        """a, b, h must be exact rational numbers (see _coerce); they are stored as int, or as
        Fraction if not integral. Raises TypeError for other types, e.g. floats."""
        a, b, h = self._coerce(a), self._coerce(b), self._coerce(h)
        self.a = a
        self.b = b
        self.h = h
        det = a * b - h * h  # Signed determinant, distinguishes definite and indefinite forms
        self.disc = abs(det)
        if all(self._is_integer(x) for x in (a, b, h)):
            g = math.gcd(int(a), int(b), int(h))
            self.exp = int(self.disc) // g if g != 0 else 0  # The zero form has exponent 0
        else:
            self.exp = None
        self.A = imat([[a, h], [h, b]])

        self.zero: List[Tuple[Any, Any]] = []
        self.river: List[BinBasis] = []
        self.pos: List[BinBasis] = []
        self.neg: List[BinBasis] = []
        self.shift: Optional[Tuple[Any, Any, Any, Any]] = None
        self.can: Optional[BinBasis] = None

        self._initialize_lattice(det)

    @staticmethod
    def _coerce(val: Any) -> Any:
        """Converts an exact rational number to int (integer types: int, numpy integers,
        flint.fmpz, sympy.Integer, ...) or to Fraction (Fraction, flint.fmpq, sympy.Rational, ...),
        using int if the value is integral. Inexact or non-numeric values (float, complex, str,
        None, ...) and bool raise TypeError: floats would make the algorithms loop forever,
        as the river of an irrational form never closes."""
        if isinstance(val, bool):
            raise TypeError("Gram matrix entries must be exact rational numbers, not bool")
        if hasattr(val, '__index__'):
            return val.__index__()
        if hasattr(val, 'numerator') and hasattr(val, 'denominator'):
            q = Fraction(int(val.numerator), int(val.denominator))
            return q.numerator if q.denominator == 1 else q
        raise TypeError(f"Gram matrix entries must be exact rational numbers, not {type(val).__name__}")

    @staticmethod
    def _is_integer(val: Any) -> bool:
        """Checks whether a coerced entry (int or non-integral Fraction) is an integer."""
        return isinstance(val, int)

    @staticmethod
    def _is_even(val: Any) -> bool:
        """Checks whether a coerced entry is an even integer."""
        return isinstance(val, int) and val % 2 == 0

    @staticmethod
    def _residue(x: Any, y: Any) -> Any:
        """Residue of x mod y, for ints and Fractions."""
        return x % y

    def _initialize_lattice(self, det: Any) -> None:
        """Dispatches on the type of the form (zero, degenerate, definite, indefinite), using
        the signed determinant det, and sets the parity."""
        if self.a == 0 and self.b == 0 and self.h == 0:
            self.signature = (0, 0)
            self.can = BinBasis((1, 0), (0, 1), self.a, self.b, self.h)
        elif det == 0:
            self._init_degenerate()
        elif det > 0:
            self._init_definite()
        else:
            self._init_indefinite()
        # Determine parity if applicable (only for integral lattices)
        if not self._is_integer(self.h):
            self.parity = None
        elif self._is_even(self.a) and self._is_even(self.b):
            self.parity = 0
        elif self._is_integer(self.a) and self._is_integer(self.b):
            self.parity = 1
        else:
            self.parity = None

    def _init_degenerate(self) -> None:
        """Nonzero form with det = 0: the norm is m (p x + q y)^2. descend() finds the kernel
        vector e, the canonical basis is (e, f) with Gram data (0, m, 0), and the seed is the
        edge (f, f + e), both of norm m."""
        self.can = self.descend(BinBasis((1, 0), (0, 1), self.a, self.b, self.h))
        self.zero = [self.can.e, (-self.can.e[0], -self.can.e[1])]
        e, f = self.can.f, self.can.sum()

        if self.a > 0 or self.b > 0:
            self.signature = (1, 0)
            self.pos = [BinBasis(e, f, self.sqr(e), self.sqr(f), self.prod(e, f))]
        else:
            self.signature = (0, 1)
            self.neg = [BinBasis(e, f, self.sqr(e), self.sqr(f), self.prod(e, f))]

    def _init_definite(self) -> None:
        """Definite form: can is the well (e, f), with s = e + f. The seeds are the three edges
        leaving the well, whose sums are e - f, 2e + f and e + 2f, so that exploring from them
        reaches every primitive vector up to sign."""
        self.can = self.descend(BinBasis((1, 0), (0, 1), self.a, self.b, self.h))
        s = self.can.sum()

        if self.a > 0:
            self.signature = (2, 0)
            target_list = self.pos
        else:
            self.signature = (0, 2)
            target_list = self.neg

        target_list.extend([
            self.can.flip(),
            BinBasis(self.can.e, s, self.can.a, self.sqr(s), self.prod(self.can.e, s)),
            BinBasis(self.can.f, s, self.can.b, self.sqr(s), self.prod(self.can.f, s))
        ])

    def _init_indefinite(self) -> None:
        """Indefinite form: descend() reaches either an isotropic vector or the river.

        If it returns an isotropic e (a = 0), the lattice represents zero. With h > 0, f is
        reduced mod e so that b = (f, f) lies in [0, 2h). If b = 0, both basis vectors are
        isotropic and the lattice is U(h). Otherwise the basis is replaced by the river edge
        (f + t e, f + (t - 1) e) of norms (r, r - 2h), and the river is processed as usual.
        """
        self.signature = (1, 1)
        bas = self.descend(BinBasis((1, 0), (0, 1), self.a, self.b, self.h))

        if bas.h < 0:
            bas = bas.flip()

        if bas.a == 0:
            # f -> f + t e changes b by 2 t h; reduce b to its residue r mod 2h
            r = self._residue(bas.b, 2 * bas.h)
            t = (r - bas.b) // (2 * bas.h)  # Exact: r - b is a multiple of 2h
            if r == 0:
                bas.f = (bas.f[0] + t * bas.e[0], bas.f[1] + t * bas.e[1])
            else:
                e = (bas.f[0] + t * bas.e[0], bas.f[1] + t * bas.e[1])
                f = (bas.f[0] + (t - 1) * bas.e[0], bas.f[1] + (t - 1) * bas.e[1])
                bas.e, bas.f = e, f
            bas.a, bas.b, bas.h = self.sqr(bas.e), self.sqr(bas.f), self.prod(bas.e, bas.f)

        if bas.a == 0 and bas.b == 0:
            # U(h): the four isotropic vectors are +-e, +-f; there is no river
            self.can = bas if bas.h > 0 else bas.flip()
            self.zero = [self.can.e, (-self.can.e[0], -self.can.e[1]),
                         self.can.f, (-self.can.f[0], -self.can.f[1])]
            self.pos = [self.can.copy()]
            self.neg = [self.can.flip()]
        else:
            self._process_river(bas)

    def _process_river(self, bas: BinBasis) -> None:
        """Follows the river from the edge bas (a > 0 > b) and sets can, river, zero, shift and
        the seeds pos, neg.

        Case 1: the river ends at a lake (the sum of its last edge is isotropic), so the lattice
        represents zero. The river is followed back from that end to the other lake. The
        isotropic vectors s1, s2 are the sums of the end edges bas1, bas2, and the edges along
        the lake shores, (s1, e1), (s1, f1), ..., are added to the seeds.

        Case 2: the river is periodic. can is the smallest edge of one period, and shift maps
        the first edge of the period to the first edge of the next one.

        In both cases, the consecutive positive (resp. negative) vectors along the banks of the
        river form the remaining seed edges.
        """
        river = self.flow(bas)
        bas1 = river[-1]

        if bas1.a + bas1.b + 2 * bas1.h == 0:
            # Case 1: e1 + f1 is isotropic. Flow in the opposite direction to the other lake.
            river = self.flow(bas1.flip())
            bas2 = river[-1]
            self.can = bas1.flip() if bas1 < bas2 else bas2.flip()
            self.river = self.flow(self.can)
            s1, s2 = bas1.sum(), bas2.sum()
            self.zero = [s1, (-s1[0], -s1[1]), s2, (-s2[0], -s2[1])]

            b1 = BinBasis(s1, bas1.e, 0, bas1.a, self.prod(s1, bas1.e))
            b2 = BinBasis(s2, bas2.e, 0, bas2.a, self.prod(s2, bas2.e))
            self.pos = [b1.copy() if b1.h > 0 else b1.flip(), b2.copy() if b2.h > 0 else b2.flip()]

            b1_neg = BinBasis(s1, bas1.f, 0, bas1.b, self.prod(s1, bas1.f))
            b2_neg = BinBasis(s2, bas2.f, 0, bas2.b, self.prod(s2, bas2.f))
            self.neg = [b1_neg.copy() if b1_neg.h < 0 else b1_neg.flip(),
                        b2_neg.copy() if b2_neg.h < 0 else b2_neg.flip()]
            self.shift = None
        else:
            # Case 2: periodic river
            nmin = min(range(len(river)), key=river.__getitem__)
            self.can = river[nmin].copy() if river[nmin].h > 0 else river[nmin].flip()
            self.river = self.flow(self.can)
            # The edge after one period of self.river has the Gram data of can, and equals can S.
            # (A period has at least 2 edges, so flow(self.river[-1]) has a second element.)
            nxt = self.flow(self.river[-1])[1]
            Ainv, det = inv2x2(self.can.imat())  # The determinant is 1 or -1
            self.shift = det * Ainv @ nxt.imat()
            # Append the next edge to the river from bas, to get the seeds of one full period
            river.append(self.flow(river[-1])[1])

        # Seed edges along the two banks of the river
        for r1, r2 in zip(river[:-1], river[1:]):
            if r1.e != r2.e:
                b = BinBasis(r1.e, r2.e, r1.a, r2.a, self.prod(r1.e, r2.e))
                self.pos.append(b.copy() if b.h > 0 else b.flip())
            if r1.f != r2.f:
                b = BinBasis(r1.f, r2.f, r1.b, r2.b, self.prod(r1.f, r2.f))
                self.neg.append(b.copy() if b.h < 0 else b.flip())

    @staticmethod
    def _normalize(u: Tuple[Any, Any]) -> Tuple[Any, Any]:
        """Chooses the sign of u: the first nonzero coordinate becomes positive."""
        if u[0] > 0 or (u[0] == 0 and u[1] > 0):
            return u
        return (-u[0], -u[1])

    def is_isomorphic(self, other: 'BinLattice', oriented: bool = False) -> bool:
        """Checks whether the two lattices are isomorphic (GL_2(Z)-equivalent) by comparing the
        signatures and the canonical Gram data.

        With oriented = True, checks for an orientation-preserving isomorphism
        (SL_2(Z)-equivalence). If the canonical Gram data agree, the isometry sending self.can
        to other.can has determinant det(self.can) det(other.can). If it is -1, the lattices
        are still oriented-isomorphic iff the lattice has an automorphism of determinant -1.
        """
        if not isinstance(other, BinLattice):
            raise TypeError(f"Expected a BinLattice, not {type(other).__name__}")
        if self.signature != other.signature:
            return False
        if (self.can.a, self.can.b, self.can.h) != (other.can.a, other.can.b, other.can.h):
            return False
        if not oriented or self._det(self.can) == self._det(other.can):
            return True
        return self.improper_automorphism() is not None

    @staticmethod
    def _det(bas: BinBasis) -> Any:
        """The determinant of the matrix with rows e, f; equal to +1 or -1 for a basis of Z^2."""
        return bas.e[0] * bas.f[1] - bas.e[1] * bas.f[0]

    def improper_automorphism(self) -> Optional[IMat]:
        """Returns an automorphism of determinant -1 (as a 2x2 matrix S acting on row vectors,
        v -> v S, with S A S^T = A), or None if there is none.

        Every basis B with the canonical Gram data (can.a, can.b, can.h) is the image of can
        under an automorphism, namely can^{-1} B, of determinant det(can) det(B). So it suffices
        to search such bases B with det(B) = -det(can):
        - zero form and degenerate lattices: B = (-e, f) (here can.h = 0);
        - U(h): B = (f, e);
        - definite: pairs of vectors of norms can.a, can.b with product can.h, from
          list_positive / list_negative (finitely many);
        - indefinite: B has (e, e) > 0 > (f, f), so it is an edge of the river, and up to
          the proper automorphism shift it is an edge in river or its flip.
        """
        can = self.can
        d0 = self._det(can)
        target = (can.a, can.b, can.h)
        candidates: List[BinBasis] = []
        if self.disc == 0:
            candidates = [BinBasis((-can.e[0], -can.e[1]), can.f, can.a, can.b, can.h)]
        elif can.a == 0 and can.b == 0:
            candidates = [can.swap()]
        elif self.signature in ((2, 0), (0, 2)):
            listing = self.list_positive if self.signature == (2, 0) else self.list_negative
            vecs = listing(abs(can.b))  # |can.a| <= |can.b|
            us = [w for u in vecs.get(can.a, ()) for w in (u, (-u[0], -u[1]))]
            vs = [w for v in vecs.get(can.b, ()) for w in (v, (-v[0], -v[1]))]
            candidates = [BinBasis(u, v, can.a, can.b, can.h) for u in us for v in vs if self.prod(u, v) == can.h]
        else:
            candidates = [B for R in self.river for B in (R, R.flip()) if (B.a, B.b, B.h) == target]
        for B in candidates:
            if self._det(B) == -d0:
                can_inv, d = inv2x2(can.imat())
                return d * can_inv @ B.imat()  # can^{-1} B, as det(can) = d = +-1
        return None

    def discriminant_form(self) -> BinDiscForm:
        """The discriminant form on L^*/L (see BinDiscForm), for a nondegenerate integral lattice.

        With the Smith normal form U A V = diag(d1, d2), the dual lattice is
        L^* = Z^2 A^{-1} = Z^2 diag(d1, d2)^{-1} U, so the rows of U divided by d1, d2
        generate L^*/L = Z/d1 x Z/d2.
        """
        if self.disc == 0 or self.exp is None:
            raise ValueError("The discriminant form is defined for nondegenerate integral lattices")
        D, U, _ = smith_normal_decomp(Matrix([[int(x) for x in row] for row in self.A.tolist()]), domain=ZZ)
        d1, d2 = abs(int(D[0, 0])), abs(int(D[1, 1]))
        g1 = (Fraction(int(U[0, 0]), d1), Fraction(int(U[0, 1]), d1))
        g2 = (Fraction(int(U[1, 0]), d2), Fraction(int(U[1, 1]), d2))
        mod = 2 if self.parity == 0 else 1
        return BinDiscForm((d1, d2), (g1, g2), self.prod(g1, g1) % mod, self.prod(g2, g2) % mod,
                           self.prod(g1, g2) % 1, mod)

    def is_same_genus(self, other: 'BinLattice') -> bool:
        """Checks whether the two lattices are in the same genus (isomorphic over Z_p for all p
        and over R).

        Even lattices of the same rank are in the same genus iff they have the same signature
        and isomorphic discriminant quadratic forms (Nikulin, Cor. 1.9.4). For odd lattices only
        q mod Z is defined on L^*/L, and Nikulin's theorem does not apply; instead L(2) and M(2),
        which are even, are compared, as the genus is invariant under rescaling. (For binary
        lattices, comparing the forms q mod Z of L and M also suffices: the 2-adic units of the at
        most two Jordan components are determined up to the Conway-Sloane equivalences by the
        determinant and the oddity formula. This was checked on all odd classes with |a|, |b| <= 60,
        |h| <= 24, but is not used here.)
        For degenerate lattices and the zero form, L is the orthogonal sum of its kernel and
        <m>, and the genus is the isomorphism class.
        """
        if not isinstance(other, BinLattice):
            raise TypeError(f"Expected a BinLattice, not {type(other).__name__}")
        if self.exp is None or other.exp is None:
            raise ValueError("The genus is defined for integral lattices")
        if self.signature != other.signature or self.disc != other.disc or self.parity != other.parity:
            return False
        if self.disc == 0:
            return self.is_isomorphic(other)
        if self.parity == 0:
            return self.discriminant_form().is_isomorphic(other.discriminant_form())
        L2 = BinLattice(2 * self.a, 2 * self.b, 2 * self.h)
        M2 = BinLattice(2 * other.a, 2 * other.b, 2 * other.h)
        return L2.discriminant_form().is_isomorphic(M2.discriminant_form())

    def list_positive(self, bound: Any) -> Dict[Any, Set[Tuple[Any, Any]]]:
        """Lists primitive vectors v with 0 < (v, v) <= |bound|, as a dict
        norm -> set of vectors, each vector up to sign (see _normalize).

        Explores the topograph from the seed edges in pos: an edge (e, f) with h >= 0 is
        followed by (e, e + f) and (f, e + f) while the norm of e + f stays within the bound.

        The list is complete for definite lattices and for indefinite lattices representing
        zero. Otherwise there are infinitely many such vectors, and the list contains one
        vector from each orbit of a group of automorphisms:
        - periodic river: the group generated by shift (and -1); see _one_per_orbit;
        - degenerate lattice: the automorphisms f -> f + t e fixing the kernel vector e;
          see _list_degenerate.
        """
        if self.disc == 0:
            return self._list_degenerate(bound, 1)
        p = list(self.pos)
        vals = defaultdict(set)

        for bas in p:
            if abs(bound) >= bas.a > 0:
                vals[bas.a].add(self._normalize(bas.e))
            if abs(bound) >= bas.b > 0:
                vals[bas.b].add(self._normalize(bas.f))

        while p:
            bas = p.pop()
            s = bas.sum()
            c = self.sqr(s)
            if 0 < c <= abs(bound):
                vals[c].add(self._normalize(s))
                p.append(BinBasis(bas.e, s, bas.a, c, self.prod(bas.e, s)))
                p.append(BinBasis(bas.f, s, bas.b, c, self.prod(bas.f, s)))
        return self._one_per_orbit(vals)

    def list_negative(self, bound: Any) -> Dict[Any, Set[Tuple[Any, Any]]]:
        """Lists primitive vectors v with -|bound| <= (v, v) < 0, as a dict norm -> set of
        vectors, each up to sign. Same method and caveats as list_positive, starting from
        the seed edges in neg."""
        if self.disc == 0:
            return self._list_degenerate(bound, -1)
        p = list(self.neg)
        vals = defaultdict(set)

        for bas in p:
            if -abs(bound) <= bas.a < 0:
                vals[bas.a].add(self._normalize(bas.e))
            if -abs(bound) <= bas.b < 0:
                vals[bas.b].add(self._normalize(bas.f))

        while p:
            bas = p.pop()
            s = bas.sum()
            c = self.sqr(s)
            if 0 > c >= -abs(bound):
                vals[c].add(self._normalize(s))
                p.append(BinBasis(bas.e, s, bas.a, c, self.prod(bas.e, s)))
                p.append(BinBasis(bas.f, s, bas.b, c, self.prod(bas.f, s)))
        return self._one_per_orbit(vals)

    def _one_per_orbit(self, vals: Dict[Any, Set[Tuple[Any, Any]]]) -> Dict[Any, Set[Tuple[Any, Any]]]:
        """For a periodic river, keeps one vector from each orbit of the group generated by
        shift and -1. The listing from the seeds covers one period of the river including
        both ends, so the only repetitions are pairs v, v S. Other automorphisms (e.g.
        reflections reversing the river) are not taken into account. Without a shift,
        returns vals unchanged."""
        if self.shift is None:
            return dict(vals)
        S = self.shift
        S_inv, _ = inv2x2(S)  # det S = 1, so the adjugate is the inverse
        result = {}
        for norm, vecs in vals.items():
            kept = set()
            for v in sorted(vecs):
                images = {self._normalize(tuple((imat(v) @ T).tolist())) for T in (S, S_inv)}
                if not images & kept:
                    kept.add(v)
            result[norm] = kept
        return result

    def _list_degenerate(self, bound: Any, sign: int) -> Dict[Any, Set[Tuple[Any, Any]]]:
        """list_positive (sign = 1) or list_negative (sign = -1) for a degenerate lattice or
        the zero form.

        With the canonical basis (e, f), e spanning the kernel and (f, f) = m, the primitive
        vectors are v = k f + l e with gcd(k, l) = 1, of norm m k^2. The automorphisms
        f -> f + t e map v to k f + (l + t k) e, so one vector of each orbit is given by
        k > 0 and 0 <= l < k."""
        e, f, m = self.can.e, self.can.f, self.can.b
        vals = defaultdict(set)
        if m == 0 or (m > 0) != (sign > 0):
            return {}
        k = 1
        while abs(m) * k * k <= abs(bound):
            for l in range(k):
                if math.gcd(k, l) == 1:
                    vals[m * k * k].add(self._normalize((k * f[0] + l * e[0], k * f[1] + l * e[1])))
            k += 1
        return dict(vals)

    def is_root(self, r: Tuple[Any, Any]) -> bool:
        """Checks whether r is a root: a primitive vector with (r, r) != 0, such that the
        reflection x -> x - 2 (x, r) / (r, r) r preserves the lattice, i.e. (r, r) divides
        2 (x, r) for both standard basis vectors x. Non-primitive vectors are never roots.
        Uses _residue, so that it also works for rational entries of the Gram matrix."""
        norm_sq = self.sqr(r)
        if norm_sq == 0 or math.gcd(*r) != 1:
            return False
        # Calculate projection scalars
        val1 = 2 * (self.a * r[0] + self.h * r[1])
        val2 = 2 * (self.h * r[0] + self.b * r[1])
        # Verify both scalars yield an integer when divided by the norm
        return self._residue(val1, norm_sq) == 0 and self._residue(val2, norm_sq) == 0

    def list_roots(self) -> Dict[Any, Set[Tuple[Any, Any]]]:
        """Lists the primitive roots, as a dict norm -> set of roots, each up to sign.

        For a primitive root r of a nondegenerate lattice, |(r, r)| divides 2 div(r), where
        div(r) is the divisibility of r, which divides disc. So it suffices to search norms
        with |(r, r)| <= 2 disc. Roots do not change under rescaling, so for a rational
        lattice with common denominator D (L(D) integral) the bound is 2 D disc. For a
        degenerate lattice, r = k f + l e (see _list_degenerate) is a root iff k divides 2,
        so the bound is 4 |m|. Same completeness caveats as list_positive.
        """
        # Roots are invariant under rescaling: for a rational lattice use the bound of L(D)
        D = math.lcm(*(Fraction(x).denominator for x in (self.a, self.b, self.h)))
        bound = 2 * D * self.disc if self.disc != 0 else 4 * abs(self.can.b)
        p = self.list_positive(bound)
        n = self.list_negative(bound)
        roots = defaultdict(set)

        for pool in (p, n):
            for v, vectors in pool.items():
                r = {x for x in vectors if self.is_root(x)}
                if r:
                    roots[v] |= r
        return dict(roots)

    def info(self) -> str:
        """A human-readable summary: parity, signature, determinant, isotropic vectors,
        canonical basis and form, and the length of the river."""
        if self.signature == (0, 0):
            return 'Zero lattice'

        if self.parity != None:
            parity = 'Even' if self.parity == 0 else 'Odd'
        else:
            parity = 'Non-integral'

        lines = [
            f"{parity} lattice of signature {self.signature} and discriminant {self.disc}"
        ]

        if self.zero:
            lines.append("Represents zero at " + ', '.join(f"{x}" for x in self.zero))
        else:
            lines.append("Does not represent zero")

        lines.append(f"Canonical basis: {self.can.e}, {self.can.f}")
        lines.append(f"Canonical form: {self.can.a}, {self.can.b}, {self.can.h}")

        if self.river:
            lines.append(f"River length: {len(self.river)}")

        return '\n'.join(lines) + '\n'

    def min_positive(self) -> Optional[Any]:
        """The minimal positive norm, or None if there is none. By the climbing lemma it is
        attained on the seed edges (next to the well, the river or the lakes) or their sums;
        the sum is needed for U(h), whose only seed consists of two isotropic vectors."""
        v = {self.sqr(w) for x in self.pos for w in (x.e, x.f, x.sum())}
        positive_vals = {n for n in v if n > 0}
        return min(positive_vals) if positive_vals else None

    def max_negative(self) -> Optional[Any]:
        """The maximal negative norm (the closest to 0), or None if there is none."""
        v = {self.sqr(w) for x in self.neg for w in (x.e, x.f, x.sum())}
        negative_vals = {n for n in v if n < 0}
        return max(negative_vals) if negative_vals else None

    def prod(self, u: Tuple[Any, Any], v: Tuple[Any, Any]) -> Any:
        """The bilinear form (u, v) on coordinate vectors."""
        if len(u) != 2 or len(v) != 2:
            raise ValueError("Vectors of a binary lattice have 2 coordinates")
        return self.a * u[0] * v[0] + self.b * u[1] * v[1] + self.h * (u[0] * v[1] + v[0] * u[1])

    def sqr(self, u: Tuple[Any, Any]) -> Any:
        """The norm (u, u)."""
        return self.prod(u, u)

    def descend(self, bas: BinBasis) -> BinBasis:
        """Climbs down the topograph from the edge bas, towards smaller absolute values of the
        norms.

        If (e, e)(f, f) <= 0 already, returns bas, swapped so that a = 0 or a > 0.
        Otherwise works with the form made positive on bas (negating it if a < 0) and with
        h <= 0 (flipping f if needed), so that the third vector of the superbase is
        -(e + f), with norm c = a + b + 2h. Each step replaces f (if a + h < 0) or e
        (if b + h < 0) by e + f, which decreases the norm and keeps h < 0. A run of steps
        of the same kind is done at once (see _run), so the number of iterations is
        logarithmic in the entries, as in Euclid's algorithm. It stops:

        - definite lattice: at the well, an obtuse superbase {e, f, -(e + f)} (all three
          pairwise products <= 0 for the positive form). Returns the basis of its two
          vectors of smallest absolute norm, with Gram data of the original form;
        - indefinite or degenerate lattice: at the first edge whose norms do not have the
          same sign. Returns it, with Gram data of the original form, swapped so that
          a = 0 (an isotropic vector) or a > 0 > b (an edge of the river).
        """
        if bas.a * bas.b == 0:
            return bas.copy() if bas.a == 0 else bas.swap()
        elif bas.a * bas.b < 0:
            return bas.copy() if bas.a > 0 else bas.swap()

        b0 = bas.negate() if bas.a < 0 else bas.copy()
        bn = b0.flip() if b0.h > 0 else b0

        while bn.a * bn.b > 0:
            if bn.a + bn.h < 0:
                # (e, e + f) = a + h < 0: replace f by e + f, m times
                m = self._run(bn.a, bn.b, bn.h)
                bn.f = (bn.f[0] + m * bn.e[0], bn.f[1] + m * bn.e[1])
                bn.b, bn.h = bn.b + 2 * m * bn.h + m * m * bn.a, bn.h + m * bn.a
            elif bn.b + bn.h < 0:
                # (f, e + f) = b + h < 0: replace e by e + f, m times
                m = self._run(bn.b, bn.a, bn.h, yield_to_other=True)
                bn.e = (bn.e[0] + m * bn.f[0], bn.e[1] + m * bn.f[1])
                bn.a, bn.h = bn.a + 2 * m * bn.h + m * m * bn.b, bn.h + m * bn.b
            else:
                # The well: take the two vectors of the superbase with the smallest norms
                c = bn.a + bn.b + 2 * bn.h
                gn = bn.sum()
                triple = sorted([(bn.a, bn.e), (bn.b, bn.f), (c, (-gn[0], -gn[1]))], key=lambda x: x[0])
                e, f = triple[0][1], triple[1][1]
                return BinBasis(e, f, self.sqr(e), self.sqr(f), self.prod(e, f))

        bn = BinBasis(bn.e, bn.f, self.sqr(bn.e), self.sqr(bn.f), self.prod(bn.e, bn.f))
        if bn.a * bn.b == 0:
            return bn if bn.a == 0 else bn.swap()
        return bn if bn.a > 0 else bn.swap()

    @staticmethod
    def _run(x: Any, y: Any, h: Any, yield_to_other: bool = False) -> int:
        """The length m of a run of steps v -> v + w in descend(), where (w, w) = x > 0,
        (v, v) = y > 0, (w, v) = h and x + h < 0.

        After t steps, (w, v + t w) = h + t x and the norm of v + t w is
        y_t = y + 2 t h + t^2 x. A step is taken while h + t x < -x, i.e. for t < k with
        k = -((x + h) // x), and while y_t > 0 (the loop condition of descend). With
        yield_to_other (the run replacing e, which descend checks second), the run also
        stops as soon as the other step applies, i.e. y_t + h + t x < 0. During the run,
        y_t and y_t + h + t x decrease, so the stopping condition is monotone in t and
        m = min(k, first t >= 1 where it holds) is found by bisection.
        """
        k = -((x + h) // x)

        def stop(t):
            y_t = y + 2 * t * h + t * t * x
            return y_t <= 0 or (yield_to_other and y_t + h + t * x < 0)

        if not stop(k):
            return k
        lo, hi = 1, k
        while lo < hi:
            mid = (lo + hi) // 2
            if stop(mid):
                hi = mid
            else:
                lo = mid + 1
        return lo

    def flow(self, bas: BinBasis) -> List[BinBasis]:
        """Follows the river starting from the edge bas, which must satisfy
        (e, e)(f, f) < 0 (otherwise returns []).

        The edge is oriented so that a > 0 > b. Each step replaces e by e + f if
        c = (e + f, e + f) > 0, and f by e + f otherwise, so that a > 0 > b is preserved; the
        sign of h determines the direction of the flow (see BinBasis.flip). It stops when
        either the sum e + f of the last edge is isotropic (the river reaches a lake), or the
        Gram data returns to that of the first edge (one full period of a periodic river).

        Returns the list of edges visited, starting with bas (swapped if needed). In the
        first case, the sum of the last edge is isotropic; in the second case, the next step
        after the last edge gives an edge with the Gram data of the first one.
        """
        if bas.a * bas.b >= 0:
            return []

        b0 = bas if bas.a > 0 else bas.swap()
        bn = b0.copy()
        river = []

        while bn.a * bn.b < 0:
            river.append(bn.copy())
            c = bn.a + bn.b + 2 * bn.h
            g = bn.sum()

            if c > 0:
                # (e + f, f) = h + b
                bn.a, bn.e, bn.h = c, g, bn.h + bn.b
            else:
                # (e, e + f) = h + a
                bn.b, bn.f, bn.h = c, g, bn.h + bn.a

            if (bn.a, bn.b, bn.h) == (b0.a, b0.b, b0.h):
                break

        return river


def list_bin_lattices(max_d, signature=None, parity=None):
    """Lists representatives of the isomorphism classes of nondegenerate binary lattices with
    0 < |det| <= max_d, as a dict |det| -> list of BinLattice (the key is BinLattice.disc),
    one lattice per class. Degenerate lattices are excluded: there are infinitely many
    classes with det = 0, namely (0, m, 0) for every m != 0.

    max_d: a nonnegative integer (TypeError for other types, ValueError if negative).
    signature: restricts to one signature, (2, 0), (0, 2) or (1, 1). With None, all
        three are listed.
    parity: 0 for even, 1 for odd, None for both.
    Other values of signature and parity raise ValueError.

    Method: first the indefinite lattices representing zero, which are all isomorphic to
    (0, b, h) with 0 <= b <= 2h and det = -h^2. Then all forms (a, b, h) with
    |a| <= 2 sqrt(max_d / 3) and 0 <= h < |a|. Every definite lattice has a reduced basis
    with |a| <= 2 sqrt(det / 3), and every indefinite lattice has a nonzero norm of
    absolute value at most 2 sqrt(|det| / 5) (Markov), which can be taken as a; h is then
    reduced mod a and made nonnegative by a flip. Each new lattice is compared with the
    ones found so far using is_isomorphic.
    """
    max_d = operator.index(max_d)  # TypeError for non-integers
    if max_d < 0:
        raise ValueError("max_d must be nonnegative")
    if signature not in (None, (2, 0), (0, 2), (1, 1)):
        raise ValueError(f"Invalid signature {signature}: expected None, (2, 0), (0, 2) or (1, 1)")
    if parity not in (None, 0, 1):
        raise ValueError(f"Invalid parity {parity}: expected None, 0 (even) or 1 (odd)")
    ll = defaultdict(list)
    max_a = math.isqrt(4 * max_d // 3) + 1  # floor(2 sqrt(max_d / 3)) + 1, exactly
    if signature == None or signature == (1, 1):
        # Listing the indefinite lattices that represent zero
        max_h = math.isqrt(max_d) + 1
        for h, b in [(h, b) for h in range(1, max_h) for b in range(2 * h + 1)]:
            if parity != None and b % 2 != parity:
                continue
            lat = BinLattice(0, b, h)
            if all(lat.is_isomorphic(l) == False for l in ll[lat.disc]):
                ll[lat.disc].append(lat)
    # Listing the positive and the rest of the indefinite lattices
    for a, h in [(a, h) for a in range(-max_a, max_a) for h in range(abs(a)) if a != 0]:
        max_b = (max_d + h * h) // abs(a) + 1
        for b in range(-max_b, max_b):
            d = abs(a * b - h * h)
            if d == 0 or d > max_d:
                continue
            # The lattice is odd iff a or b is odd
            if parity != None and int(a % 2 != 0 or b % 2 != 0) != parity:
                continue
            lat = BinLattice(a, b, h)
            if signature != None and lat.signature != signature:
                continue
            if all(lat.is_isomorphic(l) == False for l in ll[lat.disc]):
                ll[lat.disc].append(lat)
    return ll
